# BEGIN explicit absence assertion.
expect_no_match() {
  local status
  if grep "$@"; then
    echo "unexpected source pattern accepted by privacy SDK guard" >&2
    exit 1
  else
    status=$?
    if [[ "${status}" -ne 1 ]]; then
      echo "privacy SDK source-pattern check could not read its input" >&2
      exit "${status}"
    fi
  fi
}
# END explicit absence assertion.

expect_failure() {
  local expected="$1"
  shift
  local output
  if output="$("$@" 2>&1)"; then
    echo "expected command to fail: $*" >&2
    exit 1
  fi
  case "${output}" in
    *"${expected}"*) ;;
    *)
      echo "failure did not contain '${expected}': ${output}" >&2
      exit 1
      ;;
  esac
}

expect_failure_first_line() {
  local expected="$1"
  shift
  local output first_line
  if output="$("$@" 2>&1)"; then
    echo "expected command to fail: $*" >&2
    exit 1
  fi
  first_line="${output%%$'\n'*}"
  if [[ "${first_line}" != *"${expected}"* ]]; then
    echo \
      "first failure line did not contain '${expected}': ${output}" \
      >&2
    exit 1
  fi
}

expect_failure_first_diagnostic() {
  local expected="$1"
  shift
  local output first_diagnostic="" output_line
  if output="$("$@" 2>&1)"; then
    echo "expected command to fail: $*" >&2
    exit 1
  fi
  while IFS= read -r output_line; do
    case "${output_line}" in
      error:*)
        first_diagnostic="${output_line}"
        break
        ;;
    esac
  done <<<"${output}"
  if [[ -z "${first_diagnostic}" || \
    "${first_diagnostic}" != *"${expected}"* ]]; then
    echo \
      "first failure diagnostic did not contain '${expected}': ${output}" \
      >&2
    exit 1
  fi
}

ASSERT_EXACT_LINES_INDEX=0
assert_exact_lines() {
  local actual_path="$1"
  shift
  local expected_path
  ASSERT_EXACT_LINES_INDEX=$((ASSERT_EXACT_LINES_INDEX + 1))
  expected_path="${TEST_ROOT}/expected-lines-${ASSERT_EXACT_LINES_INDEX}"
  printf '%s\n' "$@" >"${expected_path}"
  if ! cmp -s "${expected_path}" "${actual_path}"; then
    echo "exact transcript drifted: ${actual_path}" >&2
    diff -u "${expected_path}" "${actual_path}" >&2 || true
    exit 1
  fi
}

