impl TryFrom<IzanamiArgs> for ChaosConfig {
    type Error = color_eyre::Report;
    fn try_from(args: IzanamiArgs) -> Result<Self> {
        if !args.allow_net {
            return Err(eyre!(
                "network orchestration disabled: pass --allow-net or set allow_net=true to run Izanami"
            ));
        }
        if !is_valid_committee_size(args.peers) {
            return Err(eyre!(
                "peer count ({}) must be an exact revision-4 3f + 1 committee in {}..={}",
                args.peers,
                MIN_VALIDATORS_PER_HEIGHT,
                MAX_VALIDATORS_PER_HEIGHT
            ));
        }
        let max_faulty_peers = (args.peers - 1) / 3;
        if args.faulty > max_faulty_peers {
            return Err(eyre!(
                "faulty peer count ({}) exceeds revision-4 fault tolerance f={} for {} peers",
                args.faulty,
                max_faulty_peers,
                args.peers
            ));
        }
        if args.duration.is_zero() {
            return Err(eyre!("duration must be greater than zero"));
        }
        if args
            .pipeline_time
            .is_some_and(|duration| duration < MIN_PIPELINE_TIME)
        {
            return Err(eyre!(
                "pipeline_time must be at least {} ms",
                MIN_PIPELINE_TIME.as_millis()
            ));
        }
        if args.target_blocks == Some(0) {
            return Err(eyre!("target_blocks must be greater than zero"));
        }
        if args.progress_interval.is_zero() {
            return Err(eyre!("progress_interval must be greater than zero"));
        }
        if args.progress_timeout.is_zero() {
            return Err(eyre!("progress_timeout must be greater than zero"));
        }
        if args.shutdown_drain_timeout.is_zero() {
            return Err(eyre!("shutdown_drain_timeout must be greater than zero"));
        }
        if args.progress_interval > args.progress_timeout {
            return Err(eyre!(
                "progress_interval ({:?}) must not exceed progress_timeout ({:?})",
                args.progress_interval,
                args.progress_timeout
            ));
        }
        if args
            .latency_p95_threshold
            .is_some_and(|duration| duration.is_zero())
        {
            return Err(eyre!("latency_p95_threshold must be greater than zero"));
        }
        if args
            .fault_window_start
            .is_some_and(|offset| offset >= args.duration)
        {
            return Err(eyre!(
                "fault_window_start ({:?}) must be before duration ({:?})",
                args.fault_window_start.expect("checked above"),
                args.duration
            ));
        }
        if args
            .fault_window_end
            .is_some_and(|offset| offset > args.duration)
        {
            return Err(eyre!(
                "fault_window_end ({:?}) must not exceed duration ({:?})",
                args.fault_window_end.expect("checked above"),
                args.duration
            ));
        }
        if let (Some(start), Some(end)) = (args.fault_window_start, args.fault_window_end)
            && end <= start
        {
            return Err(eyre!(
                "fault_window_end ({end:?}) must be after fault_window_start ({start:?})"
            ));
        }
        if args.tps <= 0.0 {
            return Err(eyre!("tps must be positive"));
        }
        if !args.tps.is_finite() {
            return Err(eyre!("tps must be finite"));
        }
        let interval_secs = 1.0 / args.tps;
        let interval = Duration::try_from_secs_f64(interval_secs)
            .map_err(|_| eyre!("tps too low for timer range"))?;
        if interval.is_zero() {
            return Err(eyre!("tps too high for timer resolution"));
        }
        if args.max_inflight == 0 {
            return Err(eyre!("max_inflight must be greater than zero"));
        }
        if args.submitters == 0 {
            return Err(eyre!("submitters must be greater than zero"));
        }
        if i64::try_from(args.sumeragi_block_max_transactions).is_err() {
            return Err(eyre!(
                "sumeragi_block_max_transactions ({}) exceeds config-layer limits",
                args.sumeragi_block_max_transactions
            ));
        }

        if args.fault_interval_min > args.fault_interval_max {
            return Err(eyre!(
                "fault interval min ({:?}) cannot be greater than max ({:?})",
                args.fault_interval_min,
                args.fault_interval_max,
            ));
        }
        let toggles = args.faults.to_toggles();
        if args.faulty > 0 && !toggles.any_enabled() {
            return Err(eyre!(
                "at least one fault scenario must be enabled when faulty peers are configured"
            ));
        }
        let IzanamiArgs {
            tui: _,
            peers,
            faulty,
            duration,
            pipeline_time,
            target_blocks,
            progress_interval,
            progress_timeout,
            shutdown_drain_timeout,
            latency_p95_threshold,
            fault_window_start,
            fault_window_end,
            seed,
            tps,
            max_inflight,
            submitters,
            prebuild_tx_buffer,
            prebuild_tx_workers,
            sumeragi_block_max_transactions,
            workload_profile,
            allow_contract_deploy_in_stable,
            log_filter,
            fault_interval_min,
            fault_interval_max,
            faults: _faults,
            nexus,
            diagnostic_dir,
            allow_net,
        } = args;
        let nexus = if nexus {
            Some(NexusProfile::sora_defaults()?)
        } else {
            None
        };
        Ok(Self {
            allow_net,
            peer_count: peers,
            faulty_peers: faulty,
            duration,
            pipeline_time,
            target_blocks,
            progress_interval,
            progress_timeout,
            shutdown_drain_timeout,
            latency_p95_threshold,
            fault_window_start,
            fault_window_end,
            seed,
            tps,
            max_inflight,
            submitters,
            prebuild_tx_buffer,
            prebuild_tx_workers,
            sumeragi_block_max_transactions,
            workload_profile,
            allow_contract_deploy_in_stable,
            fault_interval: fault_interval_min..=fault_interval_max,
            log_filter,
            faults: toggles,
            nexus,
            diagnostic_dir,
        })
    }
}
/// Initialise tracing using the resolved filter string.
pub fn init_tracing_with_filter(default_filter: &str) {
    static SUBSCRIBER: OnceLock<()> = OnceLock::new();
    SUBSCRIBER.get_or_init(|| {
        let filter = std::env::var("RUST_LOG").unwrap_or_else(|_| default_filter.to_string());
        let _ = tracing_subscriber::registry()
            .with(tracing_subscriber::EnvFilter::new(filter))
            .with(tracing_subscriber::fmt::layer())
            .try_init();
    });
}
