D_ZK = 7
N_MASK = D_ZK + 3

# ============================================================================== carry-less
_TR_S = bytes.maketrans(b"01", b"\x00\x01")
_TR_U = bytes.maketrans(b"\x00\x01", b"01")
_MASK01 = {}


def _clmul_slow(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        b >>= 1
    return r


def clmul(a, b):
    """Product in F_2[x].  Each bit is spread into one byte, the integers are multiplied
    and bit 0 of every byte of the product is the coefficient (a byte holds the number
    of contributing pairs, which is below 256 unless both operands have >= 256 set bits)."""
    if a < 2 or b < 2:
        return a * b
    sa = bin(a)[2:]
    sb = bin(b)[2:]
    if len(sa) > 255 and len(sb) > 255 and sa.count("1") > 255 and sb.count("1") > 255:
        return _clmul_slow(a, b)
    n = len(sa) + len(sb) - 1
    m = _MASK01.get(n)
    if m is None:
        m = _MASK01[n] = int.from_bytes(b"\x01" * n, "big")
    p = (int.from_bytes(sa.encode().translate(_TR_S), "big")
         * int.from_bytes(sb.encode().translate(_TR_S), "big"))
    return int((p & m).to_bytes(n, "big").translate(_TR_U), 2)


def parity(x):
    return bin(x).count("1") & 1


# ============================================================================== fields
# modulus = x^n + sum x^s for s in the tuple
FIELD_TAPS = {
    128: (0, 1, 2, 7), 192: (0, 1, 2, 7), 256: (0, 2, 5, 10),
    384: (0, 2, 3, 12), 576: (0, 3, 4, 13), 768: (0, 4, 17, 19),
}
ALPHA8 = {
    128: "0dce6055ace83fa11c9a97a955853d05",
    192: "6397386fd5a3c8cceabd6e966cd765e662366b0e14c80b31",
    256: "e7fede0b42889796674e47a0388dd6be6ae1f1f8459822df3358c920cfa8c904",
}
CHI = (0x05, 0x09, 0xF9, 0x25, 0xF4, 0x01, 0xB5, 0x8F, 0x63)


class Field:
    """F_2^n with the specification's modulus; n in FIELD_TAPS."""

    def __init__(self, n):
        self.n = n
        self.taps = FIELD_TAPS[n]
        self.mask = (1 << n) - 1
        self.nbytes = n // 8
        if n in ALPHA8:
            self.alpha8 = int.from_bytes(bytes.fromhex(ALPHA8[n]), "little")
            self.apow = [1]
            for _ in range(7):
                self.apow.append(self.mul(self.apow[-1], self.alpha8))
            self.zeta = [self.bytecombine(c) for c in CHI]
            self.nu2 = self.bytecombine(2)
            self.nu3 = self.bytecombine(3)

    def reduce(self, r):
        n, mask, taps = self.n, self.mask, self.taps
        hi = r >> n
        while hi:
            r &= mask
            for s in taps:
                r ^= hi << s
            hi = r >> n
        return r

    def mul(self, a, b):
        if a < 2 or b < 2:
            return a * b
        return self.reduce(clmul(a, b))

    def bytecombine(self, byte):
        r = 0
        for i in range(8):
            if (byte >> i) & 1:
                r ^= self.apow[i]
        return r

    def to_bytes(self, a):
        return a.to_bytes(self.nbytes, "little")


FIELDS = {}


def field(n):
    if n not in FIELDS:
        FIELDS[n] = Field(n)
    return FIELDS[n]


# ============================================================================== AES / Rijndael
def _gmul8(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a <<= 1
        if a & 0x100:
            a ^= 0x11B
        b >>= 1
    return r


def _build_sbox():
    sb = []
    for x in range(256):
        inv = 0
        if x:
            inv = 1
            for _ in range(254):
                inv = _gmul8(inv, x)
        o = 0
        for i in range(8):
            bit = ((inv >> i) ^ (inv >> ((i + 4) % 8)) ^ (inv >> ((i + 5) % 8))
                   ^ (inv >> ((i + 6) % 8)) ^ (inv >> ((i + 7) % 8)) ^ (0x63 >> i)) & 1
            o |= bit << i
        sb.append(o)
    return sb


SBOX = _build_sbox()
_MUL2 = [_gmul8(x, 2) for x in range(256)]
_MUL3 = [_gmul8(x, 3) for x in range(256)]


def rcon(i):
    r = 1
    for _ in range(i):
        r = _MUL2[r]
    return r


def key_expansion(key, nk, nst, rounds):
    """Rijndael key expansion: list of nst*(rounds+1) words, each a list of 4 bytes."""
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, nst * (rounds + 1)):
        tmp = list(w[i - 1])
        if i % nk == 0:
            tmp = tmp[1:] + tmp[:1]
            tmp = [SBOX[b] for b in tmp]
            tmp[0] ^= rcon(i // nk - 1)
        if nk > 6 and i % nk == 4:
            tmp = [SBOX[b] for b in tmp]
        w.append([a ^ b for a, b in zip(w[i - nk], tmp)])
    return w


def _shift(r, nst):
    return r if (nst != 8 or r < 2) else r + 1


def shift_rows(st, nst):
    out = [0] * (4 * nst)
    for r in range(4):
        sh = _shift(r, nst)
        for c in range(nst):
            out[4 * c + r] = st[4 * ((c + sh) % nst) + r]
    return out


def mix_columns(st, nst):
    out = [0] * (4 * nst)
    for c in range(nst):
        a0, a1, a2, a3 = st[4 * c:4 * c + 4]
        out[4 * c + 0] = _MUL2[a0] ^ _MUL3[a1] ^ a2 ^ a3
        out[4 * c + 1] = a0 ^ _MUL2[a1] ^ _MUL3[a2] ^ a3
        out[4 * c + 2] = a0 ^ a1 ^ _MUL2[a2] ^ _MUL3[a3]
        out[4 * c + 3] = _MUL3[a0] ^ a1 ^ a2 ^ _MUL2[a3]
    return out


def add_round_key(st, kw, rnd, nst):
    rk = [b for w in kw[nst * rnd:nst * (rnd + 1)] for b in w]
    return [a ^ b for a, b in zip(st, rk)]


def rijndael_encrypt(inp, kw, nst, rounds):
    st = add_round_key(list(inp), kw, 0, nst)
    for r in range(1, rounds):
        st = [SBOX[b] for b in st]
        st = shift_rows(st, nst)
        st = mix_columns(st, nst)
        st = add_round_key(st, kw, r, nst)
    st = [SBOX[b] for b in st]
    st = shift_rows(st, nst)
    return bytes(add_round_key(st, kw, rounds, nst))


# ---- fast AES (128-bit block) for the PRG: T-tables on big-endian words
def _build_te():
    te0 = []
    for s in SBOX:
        te0.append((_MUL2[s] << 24) | (s << 16) | (s << 8) | _MUL3[s])
    te1 = [((w >> 8) | (w << 24)) & 0xFFFFFFFF for w in te0]
    te2 = [((w >> 16) | (w << 16)) & 0xFFFFFFFF for w in te0]
    te3 = [((w >> 24) | (w << 8)) & 0xFFFFFFFF for w in te0]
    return te0, te1, te2, te3


TE0, TE1, TE2, TE3 = _build_te()


def _aes_round_keys(key):
    nk = len(key) // 4
    return [int.from_bytes(bytes(w), "big") for w in key_expansion(key, nk, 4, nk + 6)]


def _aes_encrypt_words(rk, s0, s1, s2, s3):
    te0, te1, te2, te3, sb = TE0, TE1, TE2, TE3, SBOX
    s0 ^= rk[0]
    s1 ^= rk[1]
    s2 ^= rk[2]
    s3 ^= rk[3]
    n = len(rk)
    i = 4
    while i < n - 4:
        t0 = te0[s0 >> 24] ^ te1[(s1 >> 16) & 255] ^ te2[(s2 >> 8) & 255] ^ te3[s3 & 255] ^ rk[i]
        t1 = te0[s1 >> 24] ^ te1[(s2 >> 16) & 255] ^ te2[(s3 >> 8) & 255] ^ te3[s0 & 255] ^ rk[i + 1]
        t2 = te0[s2 >> 24] ^ te1[(s3 >> 16) & 255] ^ te2[(s0 >> 8) & 255] ^ te3[s1 & 255] ^ rk[i + 2]
        t3 = te0[s3 >> 24] ^ te1[(s0 >> 16) & 255] ^ te2[(s1 >> 8) & 255] ^ te3[s2 & 255] ^ rk[i + 3]
        s0, s1, s2, s3 = t0, t1, t2, t3
        i += 4
    o0 = ((sb[s0 >> 24] << 24) | (sb[(s1 >> 16) & 255] << 16) | (sb[(s2 >> 8) & 255] << 8) | sb[s3 & 255]) ^ rk[i]
    o1 = ((sb[s1 >> 24] << 24) | (sb[(s2 >> 16) & 255] << 16) | (sb[(s3 >> 8) & 255] << 8) | sb[s0 & 255]) ^ rk[i + 1]
    o2 = ((sb[s2 >> 24] << 24) | (sb[(s3 >> 16) & 255] << 16) | (sb[(s0 >> 8) & 255] << 8) | sb[s1 & 255]) ^ rk[i + 2]
    o3 = ((sb[s3 >> 24] << 24) | (sb[(s0 >> 16) & 255] << 16) | (sb[(s1 >> 8) & 255] << 8) | sb[s2 & 255]) ^ rk[i + 3]
    return (o0 << 96) | (o1 << 64) | (o2 << 32) | o3


def _bswap32(x):
    return int.from_bytes(x.to_bytes(4, "little"), "big")


# ============================================================================== PRG, hashes
def prg_bytes(key, iv, twk, nbytes):
    """PRG(key, iv, twk; 8*nbytes): AES-lambda in counter mode.  The 16-byte iv is four
    little-endian u32 words; word 3 += twk and word 0 += block index, both mod 2^32,
    no carry between words.  Block i of the output is AES_key(that 16-byte block)."""
    rk = _aes_round_keys(key)
    w0 = int.from_bytes(iv[0:4], "little")
    s1 = int.from_bytes(iv[4:8], "big")
    s2 = int.from_bytes(iv[8:12], "big")
    s3 = _bswap32((int.from_bytes(iv[12:16], "little") + twk) & 0xFFFFFFFF)
    out = []
    for i in range((nbytes + 15) // 16):
        out.append(_aes_encrypt_words(rk, _bswap32((w0 + i) & 0xFFFFFFFF), s1, s2, s3)
                   .to_bytes(16, "big"))
    return b"".join(out)[:nbytes]


def prg_bits(key, iv, twk, nbits):
    """PRG output truncated to nbits: the first ceil(nbits/8) bytes, of the last byte only
    the low nbits%8 bits (bit i of the output = bit i%8 of byte i//8)."""
    v = int.from_bytes(prg_bytes(key, iv, twk, (nbits + 7) // 8), "little")
    return v & ((1 << nbits) - 1)


def shake(lam, data, nbytes):
    h = hashlib.shake_128(data) if lam == 128 else hashlib.shake_256(data)
    return h.digest(nbytes)


def H0(lam, iv, pre=b"", extended=False):
    return shake(lam, pre + iv + b"\x00", 128 if extended else 3 * lam // 8)


def H1(lam, data, pre=b""):
    return shake(lam, pre + data + b"\x01", 2 * lam // 8)


def H2(lam, j, data, nbytes, pre=b""):
    return shake(lam, pre + data + bytes([8 + j]), nbytes)


def H3(lam, data):
    out = shake(lam, data + b"\x03", lam // 8 + 16)
    return out[:lam // 8], out[lam // 8:]


def H4(lam, data, pre=b""):
    return shake(lam, pre + data + b"\x04", 16)


def H5(lam, iv, e, label, pre=b"", salt=b""):
    """n_mask-bit gate hash: SHAKE(prefix || iv || salt || LE32(e) || label || 0x05), two bytes read as a
    little-endian integer; output bit m is bit m (only bits 0..n_mask-1 are used)."""
    return int.from_bytes(shake(lam, pre + iv + salt + e.to_bytes(4, "little") + label + b"\x05", 2),
                          "little") & ((1 << N_MASK) - 1)


