SET_TABLE = {
    "faest_128s": (128, 11, 7, 102, False, "128s"),
    "faest_128f": (128, 17, 8, 108, False, "128f"),
    "faest_192s": (192, 16, 12, 162, False, "192s"),
    "faest_192f": (192, 24, 8, 163, False, "192f"),
    "faest_256s": (256, 22, 6, 225, False, "256s"),
    "faest_256f": (256, 33, 8, 229, False, "256f"),
    "faest_em_128s": (128, 11, 7, 103, True, "128s"),
    "faest_em_128f": (128, 17, 8, 105, True, "128f"),
    "faest_em_192s": (192, 16, 8, 162, True, "em_192s"),
    "faest_em_192f": (192, 25, 8, 171, True, "em_192f"),
    "faest_em_256s": (256, 22, 6, 218, True, "256s"),
    "faest_em_256f": (256, 33, 8, 229, True, "256f"),
}
_TABLES = {}


class Params:
    def __init__(self, name):
        lam, tau, w, t_open, em, profile = SET_TABLE[name]
        self.name, self.lam, self.tau, self.w, self.t_open, self.em = name, lam, tau, w, t_open, em
        self.profile = profile
        self.lb = lam // 8
        # Namespace prefix absorbed by EVERY SHAKE oracle call (H0, H1, H2^0..3, H4, H5) before
        # its body.  b"" = FAEST v3.0 reference mode.  H3 is never prefixed (ballot proofs do
        # not call it); the AES PRG and its tweaks do not depend on the prefix.
        self.prefix = b""
        self.extended = False
        self.F = field(lam)
        # Leaf-commitment variant: a parameter of the VOLE row (spec param = (lambda, tau,
        # w_grind, T_open, n_leafcom, ell, d_zk)), NOT of the relation.  The twelve sets happen
        # to pair 3 with the AES relation and 2 with EM; BAVC code reads only P.n_leafcom.
        self.n_leafcom = 2 if em else 3
        # --- VOLE parameters (Table 5.1)
        self.nd = lam - w
        self.k = self.nd // tau + 1
        self.tau1 = self.nd % tau
        self.degs = [self.k if i < self.tau1 else self.k - 1 for i in range(tau)]
        self.d0 = max(self.degs)
        self.starts = [sum(self.degs[:i]) for i in range(tau)]
        self.L = sum(1 << d for d in self.degs)
        # --- OWF parameters (Table 3.3)
        self.nk = lam // 32
        self.nst = lam // 32 if em else 4
        self.rounds = max(self.nk, self.nst) + 6
        self.beta = 1 if em else -(-lam // (32 * self.nst))
        self.ske = 0 if em else (-lam // 8 + 56 + 28 * (lam // 256))
        self.senc = 4 * self.nst * self.rounds
        self.lke = lam + 8 * self.ske
        self.lenc = (self.rounds // 2 - 1) * 32 * self.nst
        self.ell = self.lke + self.beta * self.lenc
        self.C = self.ell + 2 * self.ske + self.beta * self.senc // 2 + 1
        self.ell_hat = self.ell + N_MASK * self.d0
        self.x_bytes = 4 * self.nst
        self.y_bytes = self.beta * 4 * self.nst
        self.pk_bytes = self.x_bytes + self.y_bytes
        self.sk_bytes = self.x_bytes + self.lb
        self._t = None

    # --- CRT tables (generated on first use, shared between sets with the same profile)
    @property
    def t(self):
        if self._t is None:
            if self.profile not in _TABLES:
                t = C.generate(self.profile)
                assert (t["lambda"], t["tau"], t["w_grind"]) == (self.lam, self.tau, self.w)
                assert [C.pdeg(m) for m in t["tree_moduli"]] == self.degs
                nd, ng = self.nd, t["n_mult"]
                t["wcrt_cols"] = transpose(t["W_CRT"], nd)
                t["wtree_cols"] = transpose(t["W_TREE"], nd)
                t["wgate_cols"] = transpose(t["W_GATE"], ng)
                _TABLES[self.profile] = t
            self._t = _TABLES[self.profile]
        return self._t

    @property
    def n_mult(self):
        return self.t["n_mult"]

    @property
    def cm_row_bytes(self):
        return (self.n_mult + 7) // 8

    def sig_layout(self):
        """[(field name, offset, length)] in bytes, in signature order."""
        lb, ellb = self.lb, self.ell // 8
        fields = [
            ("c_1..c_{tau-1}", (self.tau - 1) * ellb),
            ("c_mult", N_MASK * self.cm_row_bytes),
            ("u_tilde", 4 * lb),
            ("d", ellb),
            ("a_tilde_1..a_tilde_6", (D_ZK - 1) * lb),
            ("decom_I: hidden leaf commitments", self.tau * self.leaf_bytes),
            ("decom_I: node seeds, zero padded", self.t_open * lb),
            ("chall_3", lb),
            ("iv_pre", 16),
            ("ctr", 4),
        ]
        if self.extended:
            fields.insert(-1, ("salt", 32))
        out, off = [], 0
        for name, ln in fields:
            out.append((name, off, ln))
            off += ln
        return out

    @property
    def leaf_bytes(self):
        return 112 if self.extended else self.n_leafcom * self.lb

    @property
    def sig_bytes(self):
        name, off, ln = self.sig_layout()[-1]
        return off + ln


_PARAMS = {}


def params(name):
    if name not in _PARAMS:
        _PARAMS[name] = Params(name)
    return _PARAMS[name]


def transpose(rows, ncols):
    return [sum(((rows[r] >> c) & 1) << r for r in range(len(rows))) for c in range(ncols)]


def matvec_cols(cols, v):
    """XOR of cols[j] over the set bits j of v (cols = columns of the matrix)."""
    out = 0
    j = 0
    while v:
        if v & 1:
            out ^= cols[j]
        v >>= 1
        j += 1
    return out


# ============================================================================== BAVC
def pos_in_tree(P, i, j):
    half = 1 << (P.k - 1)
    if j < half:
        return P.L - 1 + P.tau * j + i
    return P.L - 1 + P.tau * half + P.tau1 * (j % half) + i


def leaf_commit(P, key, iv, twk, uhash):
    """-> (sd, com).  n_leafcom = 3 (FAEST): PRG to 4*lambda bits, sd = first lambda bits,
    com = sd * uhash + x1 in F_2^(3 lambda).  n_leafcom = 2 (FAEST-EM): sd = key, com = PRG
    to 2*lambda bits. Extended mode adds the affine 128-bit checksum.
    The explicit variant, not the relation, determines the commitment layout."""
    lb = P.lb
    if P.n_leafcom == 2:
        return key, prg_bytes(key, iv, twk, 2 * lb)
    o = prg_bytes(key, iv, twk, 144 if P.extended else 4 * lb)
    sd = o[:lb]
    f3 = field(3 * P.lam)
    h = f3.mul(int.from_bytes(uhash[:3 * lb], "little"), int.from_bytes(sd, "little")) \
        ^ int.from_bytes(o[lb:4 * lb], "little")
    com = h.to_bytes(3 * lb, "little")
    if P.extended:
        checksum = P.F.mul(int.from_bytes(sd, "little"), int.from_bytes(uhash[96:128], "little"))
        com += bytes(a ^ b for a, b in zip(checksum.to_bytes(32, "little")[:16], o[128:144]))
    return sd, com


def bavc_commit(P, r, iv):
    """-> dict(com, keys[2L-1], coms[i][j], seeds[i][j])."""
    lb, L, tau = P.lb, P.L, P.tau
    uhash = None if P.n_leafcom == 2 else H0(P.lam, iv, P.prefix, P.extended)
    keys = [None] * (2 * L - 1)
    keys[0] = r
    for alpha in range(L - 1):
        o = prg_bytes(keys[alpha], iv, alpha, 2 * lb)
        keys[2 * alpha + 1] = o[:lb]
        keys[2 * alpha + 2] = o[lb:]
    seeds, coms, hs = [], [], []
    for i in range(tau):
        sd_i, com_i = [], []
        for j in range(1 << P.degs[i]):
            sd, com = leaf_commit(P, keys[pos_in_tree(P, i, j)], iv, i + L - 1, uhash)
            sd_i.append(sd)
            com_i.append(com)
        seeds.append(sd_i)
        coms.append(com_i)
        hs.append(H1(P.lam, b"".join(com_i), P.prefix))
    return {"com": H1(P.lam, b"".join(hs), P.prefix), "keys": keys, "coms": coms, "seeds": seeds}


def bavc_open(P, decom, idx):
    """idx = (Delta_0..Delta_{tau-1}).  -> decom_I bytes, or None (abort: more than T_open
    node seeds would be revealed)."""
    L, tau, lb = P.L, P.tau, P.lb
    out = [decom["coms"][i][idx[i]] for i in range(tau)]
    S = bytearray(2 * L - 1)
    nh = 0
    for i in range(tau):
        alpha = pos_in_tree(P, i, idx[i])
        S[alpha] = 1
        nh += 1
        while alpha > 0 and S[(alpha - 1) // 2] == 0:
            alpha = (alpha - 1) // 2
            S[alpha] = 1
            nh += 1
    if nh - 2 * tau + 1 > P.t_open:
        return None
    n = 0
    for p in range(L - 2, -1, -1):
        if S[2 * p + 1] ^ S[2 * p + 2]:
            out.append(decom["keys"][2 * p + 1 + S[2 * p + 1]])
            n += 1
    out.append(bytes((P.t_open - n) * lb))
    return b"".join(out)


def bavc_reconstruct(P, decom_i, idx, iv):
    """-> (com, seeds) with seeds[i][j] = sd_{i,j} and seeds[i][Delta_i] = None; or None
    (reject: node seeds exhausted, or non-zero bytes after the last used seed)."""
    L, tau, lb, lam = P.L, P.tau, P.lb, P.lam
    cb = P.leaf_bytes
    if len(decom_i) != tau * cb + P.t_open * lb:
        return None
    hidden = [decom_i[i * cb:(i + 1) * cb] for i in range(tau)]
    nodes = decom_i[tau * cb:]
    uhash = None if P.n_leafcom == 2 else H0(lam, iv, P.prefix, P.extended)
    S = bytearray(2 * L - 1)
    for i in range(tau):
        if not 0 <= idx[i] < (1 << P.degs[i]):
            return None
        S[pos_in_tree(P, i, idx[i])] = 1
    keys = [None] * (2 * L - 1)
    used = 0
    for p in range(L - 2, -1, -1):
        S[p] = S[2 * p + 1] | S[2 * p + 2]
        if S[2 * p + 1] ^ S[2 * p + 2]:
            if used == P.t_open:
                return None
            keys[2 * p + 1 + S[2 * p + 1]] = nodes[used * lb:(used + 1) * lb]
            used += 1
    if any(nodes[used * lb:]):
        return None
    for p in range(L - 1):
        if not S[p]:
            o = prg_bytes(keys[p], iv, p, 2 * lb)
            keys[2 * p + 1] = o[:lb]
            keys[2 * p + 2] = o[lb:]
    seeds, hs = [], []
    for i in range(tau):
        sd_i, com_i = [], []
        for j in range(1 << P.degs[i]):
            alpha = pos_in_tree(P, i, j)
            if S[alpha]:
                sd_i.append(None)
                com_i.append(hidden[i])
            else:
                sd, com = leaf_commit(P, keys[alpha], iv, i + L - 1, uhash)
                sd_i.append(sd)
                com_i.append(com)
        seeds.append(sd_i)
        hs.append(H1(lam, b"".join(com_i), P.prefix))
    return H1(lam, b"".join(hs), P.prefix), seeds


# ============================================================================== small VOLE
def convert_to_vole(rs, d):
    """rs: 2^d strings (ints).  -> (u, [v_0..v_{d-1}])."""
    vs = []
    cur = rs
    for _ in range(d):
        v = 0
        nxt = []
        for i in range(0, len(cur), 2):
            v ^= cur[i + 1]
            nxt.append(cur[i] ^ cur[i + 1])
        vs.append(v)
        cur = nxt
    return cur[0], vs


def decode_all_chall3(P, chall, ignore_grinding=False):
    """chall: lambda-bit int.  -> [Delta_0..Delta_{tau-1}] or None (non-zero grinding bits)."""
    if (chall >> P.nd) and not ignore_grinding:
        return None
    return [(chall >> P.starts[i]) & ((1 << P.degs[i]) - 1) for i in range(P.tau)]


def _tree_shares(P, cols, m):
    """rt_{m,0} || ... || rt_{m,tau-1} (n_Delta bits) for the columns `cols` (V or Q)."""
    ell_m = P.ell + m * P.d0
    mods = P.t["tree_moduli"]
    out = 0
    for i in range(P.tau):
        d, st = P.degs[i], P.starts[i]
        acc = 0
        for c in range(d):
            # column c contributes x^c * B_c(x), B_c = rows ell_m .. ell_m+d-1 of column c
            acc ^= ((cols[st + c] >> ell_m) & ((1 << d) - 1)) << c
        out |= C.pmod(acc, mods[i]) << st
    return out


def _lift_rows(P, cols):
    """[ToField(W_crt * row j of cols)] for j in [0..ell)."""
    nd, ell = P.nd, P.ell
    mask = (1 << ell) - 1
    fmt = "0%db" % ell
    wcrt = P.t["W_CRT"]
    # strs[r] = bits of (W_crt row r applied to the columns), string index j = row j
    strs = [format(C.combine(wcrt[r], cols) & mask, fmt)[::-1] for r in range(nd - 1, -1, -1)]
    return [int("".join(col), 2) for col in zip(*strs)]


def vole_commit(P, r, iv, salt=b""):
    lam, lb, ell, tau, nd, w, d0 = P.lam, P.lb, P.ell, P.tau, P.nd, P.w, P.d0
    t = P.t
    ng = t["n_mult"]
    bavc = bavc_commit(P, r, iv)
    us, vcols = [], []
    for i in range(tau):
        rs = [prg_bits(sd, iv, i + (1 << 31), P.ell_hat) for sd in bavc["seeds"][i]]
        u_i, vs = convert_to_vole(rs, P.degs[i])
        us.append(u_i)
        vcols.extend(vs)
    ell_mask = (1 << ell) - 1
    u = us[0] & ell_mask
    cs = [u ^ (us[i] & ell_mask) for i in range(1, tau)]
    # field masks
    u_hi_all = prg_bits(r, iv, (1 << 31) - 1, N_MASK * w)
    ubar = []
    for m in range(N_MASK):
        ell_m = ell + m * d0
        u_low = 0
        for i in range(tau):
            u_low |= ((us[i] >> ell_m) & ((1 << P.degs[i]) - 1)) << P.starts[i]
        u_hi = (u_hi_all >> (m * w)) & ((1 << w) - 1)
        ub = matvec_cols(t["wcrt_cols"], u_low) ^ clmul(t["m_tree"], u_hi)
        assert ub >> lam == 0
        ubar.append(ub)
    # gates
    lam_mask = (1 << lam) - 1
    a = [c & lam_mask for c in vcols]
    u_lam = u & lam_mask
    vt = [0] * N_MASK
    cm = [0] * N_MASK
    for e in range(ng):
        l0 = matvec_cols(a, t["G"][e])
        h0 = H5(lam, iv, e, l0.to_bytes(lb, "little"), P.prefix, salt)
        h1 = H5(lam, iv, e, (l0 ^ u_lam).to_bytes(lb, "little"), P.prefix, salt)
        f = t["F"][e]
        for m in range(N_MASK):
            b0 = (h0 >> m) & 1
            vt[m] |= b0 << e
            cm[m] |= (b0 ^ ((h1 >> m) & 1) ^ parity(f & ubar[m])) << e
    vbar = [matvec_cols(t["wtree_cols"], _tree_shares(P, vcols, m))
            ^ matvec_cols(t["wgate_cols"], vt[m]) for m in range(N_MASK)]
    V = _lift_rows(P, vcols)
    return {"com": bavc["com"], "decom": bavc, "cs": cs, "c_mult": cm, "u": u, "V": V,
            "ubar": ubar, "vbar": vbar}


def small_vole_reconstruct(P, chall, decom_i, iv, ignore_grinding=False):
    """The part of VOLEReconstruct that depends only on (chall_3, decom_I, iv):
    -> (com, raw q columns before the c_i correction, Delta') or None."""
    idx = decode_all_chall3(P, chall, ignore_grinding)
    if idx is None:
        return None
    rec = bavc_reconstruct(P, decom_i, idx, iv)
    if rec is None:
        return None
    com, seeds = rec
    qcols = []
    for i in range(P.tau):
        n = 1 << P.degs[i]
        rs = [0] + [prg_bits(seeds[i][j ^ idx[i]], iv, i + (1 << 31), P.ell_hat)
                    for j in range(1, n)]
        _, qs = convert_to_vole(rs, P.degs[i])
        qcols.extend(qs)
    return com, qcols, chall & ((1 << P.nd) - 1)


def vole_reconstruct(P, chall, decom_i, cs, cm, iv, ignore_grinding=False, cache=None, salt=b""):
    """-> dict(com, Q, qbar, delta) or None.  `cache` (optional dict) memoises
    small_vole_reconstruct, a deterministic function of (chall, decom_I, iv)."""
    lam, lb, ell, tau = P.lam, P.lb, P.ell, P.tau
    t = P.t
    ng = t["n_mult"]
    key = (P.name, P.prefix, chall, decom_i, iv, ignore_grinding)
    if cache is not None and key in cache:
        sv = cache[key]
    else:
        sv = small_vole_reconstruct(P, chall, decom_i, iv, ignore_grinding)
        if cache is not None:
            cache[key] = sv
    if sv is None:
        return None
    com, raw, dprime = sv
    qcols = list(raw)
    for i in range(1, tau):
        for c in range(P.degs[i]):
            j = P.starts[i] + c
            if (dprime >> j) & 1:
                qcols[j] ^= cs[i - 1]
    delta = matvec_cols(t["wcrt_cols"], dprime)
    lam_mask = (1 << lam) - 1
    aq = [c & lam_mask for c in qcols]
    qt = [0] * N_MASK
    for e in range(ng):
        g = t["G"][e]
        h = H5(lam, iv, e, matvec_cols(aq, g).to_bytes(lb, "little"), P.prefix, salt)
        if parity(g & dprime):
            for m in range(N_MASK):
                qt[m] |= (((h >> m) & 1) ^ ((cm[m] >> e) & 1)) << e
        else:
            for m in range(N_MASK):
                qt[m] |= ((h >> m) & 1) << e
    qbar = [matvec_cols(t["wtree_cols"], _tree_shares(P, qcols, m))
            ^ matvec_cols(t["wgate_cols"], qt[m]) for m in range(N_MASK)]
    return {"com": com, "Q": _lift_rows(P, qcols), "qbar": qbar, "delta": delta}


# ============================================================================== universal hashes
def vole_hash(F, sd, x0, x1):
    """sd: 8*lambda/8 + 8 bytes = r0..r3 || s0..s3 || t.  x0: list of field elements
    (ell + d_zk - 1 of them), x1: 4 elements.  -> 4 elements."""
    lb = F.nbytes
    r = [int.from_bytes(sd[i * lb:(i + 1) * lb], "little") for i in range(4)]
    s = [int.from_bytes(sd[(4 + i) * lb:(5 + i) * lb], "little") for i in range(4)]
    s.append(int.from_bytes(sd[8 * lb:8 * lb + 8], "little"))
    y = []
    for sj in s:
        acc = 0
        for v in x0:
            acc = F.mul(acc, sj) ^ v
        y.append(acc)
    return [F.mul(r[j], y[0]) ^ y[j + 1] ^ x1[j] for j in range(4)]


def zk_hash(F, sd, x0, x1):
    """sd: 3*lambda/8 + 8 bytes = r0 || r1 || s || t.  x0: C elements, x1: one element."""
    lb = F.nbytes
    r0 = int.from_bytes(sd[0:lb], "little")
    r1 = int.from_bytes(sd[lb:2 * lb], "little")
    s = int.from_bytes(sd[2 * lb:3 * lb], "little")
    t = int.from_bytes(sd[3 * lb:3 * lb + 8], "little")
    h0 = h1 = 0
    for v in x0:
        h0 = F.mul(h0, s) ^ v
        h1 = F.mul(h1, t) ^ v
    return F.mul(r0, h0) ^ F.mul(r1, h1) ^ x1


# ============================================================================== commitment back ends
class ProverBackend:
    """A degree-d commitment is the list of d+1 coefficients, lowest first; the committed
    value is the top coefficient."""

    def __init__(self, F):
        self.F = F

    def const(self, c):
        return [0, c]

    def add(self, a, b):
        la, lb = len(a), len(b)
        if la < lb:
            a = [0] * (lb - la) + a
        elif lb < la:
            b = [0] * (la - lb) + b
        return [x ^ y for x, y in zip(a, b)]

    def add_const(self, a, c):
        r = list(a)
        r[-1] ^= c
        return r

    def scale(self, a, c):
        mul = self.F.mul
        return [mul(x, c) for x in a]

    def mul(self, a, b):
        mul = self.F.mul
        r = [0] * (len(a) + len(b) - 1)
        for i, x in enumerate(a):
            if x:
                for j, y in enumerate(b):
                    if y:
                        r[i + j] ^= mul(x, y)
        return r

    def lift(self, a, f):
        return [0] * f + a


class VerifierBackend:
    """A degree-d commitment is (key, d) with key = prover polynomial evaluated at Delta."""

    def __init__(self, F, delta):
        self.F = F
        self.dp = [1]
        for _ in range(D_ZK):
            self.dp.append(F.mul(self.dp[-1], delta))

    def const(self, c):
        return (self.F.mul(c, self.dp[1]), 1)

    def add(self, a, b):
        qa, da = a
        qb, db = b
        if da == db:
            return (qa ^ qb, da)
        if da < db:
            return (self.F.mul(qa, self.dp[db - da]) ^ qb, db)
        return (qa ^ self.F.mul(qb, self.dp[da - db]), da)

    def add_const(self, a, c):
        return (a[0] ^ self.F.mul(c, self.dp[a[1]]), a[1])

    def scale(self, a, c):
        return (self.F.mul(a[0], c), a[1])

    def mul(self, a, b):
        return (self.F.mul(a[0], b[0]), a[1] + b[1])

    def lift(self, a, f):
        return (self.F.mul(a[0], self.dp[f]), a[1] + f)


# ============================================================================== AES gadgets
def bits_of(bs):
    return [(b >> i) & 1 for b in bs for i in range(8)]


def zk_bytecombine(B, x):
    apow = B.F.apow
    acc = x[0]
    for i in range(1, 8):
        acc = B.add(acc, B.scale(x[i], apow[i]))
    return acc


def _xor(B, *xs):
    acc = xs[0]
    for x in xs[1:]:
        acc = B.add(acc, x)
    return acc


def square_bits(B, x):
    return [_xor(B, x[0], x[4], x[6]), _xor(B, x[4], x[6], x[7]), _xor(B, x[1], x[5]),
            _xor(B, x[4], x[5], x[6], x[7]), _xor(B, x[2], x[4], x[7]), _xor(B, x[5], x[6]),
            _xor(B, x[3], x[5]), _xor(B, x[6], x[7])]


def conjugates(B, bits, nbytes):
    out = []
    for i in range(nbytes):
        x = bits[8 * i:8 * i + 8]
        row = []
        for _ in range(7):
            row.append(zk_bytecombine(B, x))
            x = square_bits(B, x)
        row.append(zk_bytecombine(B, x))
        out.append(row)
    return out


def inverse_affine(B, bits, nbytes):
    one = B.const(1)
    out = []
    for i in range(nbytes):
        x = bits[8 * i:8 * i + 8]
        for j in range(8):
            y = _xor(B, x[(j - 1) % 8], x[(j - 3) % 8], x[(j - 6) % 8])
            if j in (0, 2):
                y = B.add(y, one)
            out.append(y)
    return out


def inverse_sbox_eval(B, bits, nbytes):
    cj = conjugates(B, inverse_affine(B, bits, nbytes), nbytes)
    out = []
    for j in range(nbytes):
        acc = cj[j][1]
        for i in range(2, 8):
            acc = B.mul(acc, cj[j][i])
        out.append(acc)
    return out


def sbox_eval(B, bits, nbytes):
    zeta = B.F.zeta
    cj = conjugates(B, bits, nbytes)
    out = []
    for j in range(nbytes):
        c = cj[j]
        p1 = [B.mul(c[2 * i], c[2 * i + 1]) for i in range(4)]
        f1 = [B.add(B.scale(c[2 * i + 1], zeta[2 * i]), B.scale(c[2 * i], zeta[2 * i + 1]))
              for i in range(4)]
        p2 = [B.mul(p1[2 * i], p1[2 * i + 1]) for i in range(2)]
        f2 = [B.add(B.mul(f1[2 * i], p1[2 * i + 1]), B.mul(f1[2 * i + 1], p1[2 * i]))
              for i in range(2)]
        st = B.add(B.mul(f2[0], p2[1]), B.mul(f2[1], p2[0]))
        out.append(B.add_const(st, zeta[8]))
    return out


def zk_shift_rows(st, nst):
    out = [None] * (4 * nst)
    for r in range(4):
        sh = _shift(r, nst)
        for c in range(nst):
            out[4 * c + r] = st[4 * ((c + sh) % nst) + r]
    return out


def zk_inverse_shift_rows(bits, nst):
    out = [None] * (32 * nst)
    for r in range(4):
        sh = _shift(r, nst)
        for c in range(nst):
            i = 4 * ((c - sh) % nst) + r
            out[8 * (4 * c + r):8 * (4 * c + r) + 8] = bits[8 * i:8 * i + 8]
    return out


def zk_mix_columns(B, st, nst):
    nu2, nu3 = B.F.nu2, B.F.nu3
    out = [None] * (4 * nst)
    for c in range(nst):
        x = st[4 * c:4 * c + 4]
        x2 = [B.scale(v, nu2) for v in x]
        x3 = [B.scale(v, nu3) for v in x]
        out[4 * c + 0] = _xor(B, x2[0], x3[1], x[2], x[3])
        out[4 * c + 1] = _xor(B, x[0], x2[1], x3[2], x[3])
        out[4 * c + 2] = _xor(B, x[0], x[1], x2[2], x3[3])
        out[4 * c + 3] = _xor(B, x3[0], x[1], x[2], x2[3])
    return out


def zk_bitwise_mix_columns(B, bits, nst):
    out = []
    for c in range(nst):
        a = [bits[32 * c + 8 * r:32 * c + 8 * r + 8] for r in range(4)]
        b = [[x[7], B.add(x[0], x[7]), x[1], B.add(x[2], x[7]), B.add(x[3], x[7]), x[4], x[5],
              x[6]] for x in a]

        def vadd(*vs):
            return [_xor(B, *[v[i] for v in vs]) for i in range(8)]
        out += vadd(b[0], a[3], a[2], b[1], a[1])
        out += vadd(b[1], a[0], a[3], b[2], a[2])
        out += vadd(b[2], a[1], a[0], b[3], a[3])
        out += vadd(b[3], a[2], a[1], b[0], a[0])
    return out


def zk_add_round_key(B, s, k):
    return [B.add(x, y) for x, y in zip(s, k)]


def zk_add_round_key_bytes(B, st, kbits):
    return [B.add(st[i], zk_bytecombine(B, kbits[8 * i:8 * i + 8])) for i in range(len(st))]


# ============================================================================== OWF relation
def owf(P, k, x):
    """y = E_k(x): AES (one or two blocks, second input x XOR 1) or Even-Mansour."""
    if P.em:
        kw = key_expansion(x, P.nk, P.nst, P.rounds)
        c = rijndael_encrypt(k, kw, P.nst, P.rounds)
        return bytes(a ^ b for a, b in zip(c, k))
    kw = key_expansion(k, P.nk, 4, P.rounds)
    y = rijndael_encrypt(x, kw, 4, P.rounds)
    if P.beta == 2:
        y += rijndael_encrypt(bytes([x[0] ^ 1]) + bytes(x[1:]), kw, 4, P.rounds)
    return y


def extend_witness(P, k, x):
    """-> list of ell witness bits."""
    nk, nst, rounds = P.nk, P.nst, P.rounds
    w = []
    if not P.em:
        kw = key_expansion(k, nk, nst, rounds)
        for i in range(nk):
            w += bits_of(kw[i])
        ik = nk
        for _ in range(P.ske // 4):
            w += bits_of(kw[ik])
            ik += 6 if P.lam == 192 else 4
        ins = [bytes(x)]
        if P.beta == 2:
            ins.append(bytes([x[0] ^ 1]) + bytes(x[1:]))
    else:
        kw = key_expansion(x, nk, nst, rounds)
        w += bits_of(k)
        ins = [bytes(k)]
    for b in range(P.beta):
        st = add_round_key(list(ins[b]), kw, 0, nst)
        for j in range(1, rounds - 1):
            st = [SBOX[v] for v in st]
            st = shift_rows(st, nst)
            if j % 2 == 0:
                w += bits_of(st)
            st = mix_columns(st, nst)
            st = add_round_key(st, kw, j, nst)
    assert len(w) == P.ell
    return w


def key_exp_fwd(B, P, w):
    lam, nk = P.lam, P.nk
    y = list(w[:lam])
    iwd = lam
    for j in range(nk, 4 * (P.rounds + 1)):
        if j % nk == 0 or (nk > 6 and j % nk == 4):
            y += w[iwd:iwd + 32]
            iwd += 32
        else:
            y += [B.add(y[32 * (j - nk) + i], y[32 * (j - 1) + i]) for i in range(32)]
    assert iwd == P.lke
    return y


def key_exp_bkwd(B, P, x, xkey):
    lam = P.lam
    one = B.const(1)
    y = []
    iwd = 0
    rcon_evry = 4 * (lam // 128)
    for j in range(P.ske):
        xt = []
        for i in range(8):
            t = B.add(x[8 * j + i], xkey[iwd + 8 * (j % 4) + i])
            if j % rcon_evry == 0 and (rcon(j // rcon_evry) >> i) & 1:
                t = B.add(t, one)
            xt.append(t)
        y += inverse_affine(B, xt, 1)
        if j % 4 == 3:
            iwd += 192 if lam == 192 else 128
    return y


def key_exp_cstrnts(B, P, w):
    lam, nk = P.lam, P.nk
    k = key_exp_fwd(B, P, w)
    wbar = key_exp_bkwd(B, P, w[lam:], k)
    iwd = 32 * (nk - 1)
    do_rot = True
    z = []
    for j in range(P.ske // 4):
        khat = [None] * 4
        ksq = [None] * 4
        what = [None] * 4
        wsq = [None] * 4
        for r in range(4):
            rp = (r + 3) % 4 if do_rot else r
            kb = k[iwd + 8 * r:iwd + 8 * r + 8]
            wb = wbar[32 * j + 8 * r:32 * j + 8 * r + 8]
            khat[rp] = zk_bytecombine(B, kb)
            ksq[rp] = zk_bytecombine(B, square_bits(B, kb))
            what[r] = zk_bytecombine(B, wb)
            wsq[r] = zk_bytecombine(B, square_bits(B, wb))
        if lam == 256:
            do_rot = not do_rot
        for r in range(4):
            z.append(B.add(B.mul(ksq[r], what[r]), khat[r]))
            z.append(B.add(B.mul(khat[r], wsq[r]), what[r]))
        iwd += 192 if lam == 192 else 128
    return z, k


def enc_cstrnts(B, P, inp, out, w, rk):
    nst, rounds = P.nst, P.rounds
    nb, nbits = 4 * nst, 32 * nst
    z = []
    state_bits = zk_add_round_key(B, inp, rk[0])
    for r in range(rounds // 2):
        st = sbox_eval(B, state_bits, nb)
        st = zk_shift_rows(st, nst)
        st = zk_mix_columns(B, st, nst)
        st = zk_add_round_key_bytes(B, st, rk[2 * r + 1])
        if r == rounds // 2 - 1:
            s_t = zk_add_round_key(B, out, rk[rounds])
        else:
            s_t = w[nbits * r:nbits * (r + 1)]
        b = inverse_sbox_eval(B, zk_inverse_shift_rows(s_t, nst), nb)
        for i in range(nb):
            z.append(B.add(b[i], st[i]))
        if r != rounds // 2 - 1:
            state_bits = zk_bitwise_mix_columns(B, s_t, nst)
            state_bits = zk_add_round_key(B, state_bits, rk[2 * r + 2])
    return z


def owf_constraints(B, P, w, pk):
    """The C - ell relation constraints, each lifted to degree exactly d_zk."""
    lam, nst, rounds = P.lam, P.nst, P.rounds
    nbits = 32 * nst
    x, y = pk[:P.x_bytes], pk[P.x_bytes:]
    z = [B.lift(B.mul(w[0], w[1]), D_ZK - 2)]
    ybits = bits_of(y)
    if P.em:
        kw = key_expansion(x, P.nk, nst, rounds)
        kbits = [B.const(b) for wd in kw for b in bits_of(wd)]
        inp = list(w[:lam])
        outs = [[B.add(w[i], B.const(ybits[i])) for i in range(lam)]]
    else:
        inp = [B.const(b) for b in bits_of(x)]
        outs = [[B.const(b) for b in ybits[128 * b0:128 * b0 + 128]] for b0 in range(P.beta)]
        zt, kbits = key_exp_cstrnts(B, P, w[:P.lke])
        z += [B.lift(c, D_ZK - 2) for c in zt]
    rk = [kbits[nbits * i:nbits * (i + 1)] for i in range(rounds + 1)]
    for b in range(P.beta):
        wt = w[P.lke + b * P.lenc:P.lke + (b + 1) * P.lenc]
        if b == 1:
            inp = [B.add(inp[0], B.const(1))] + inp[1:]
        z += enc_cstrnts(B, P, inp, outs[b], wt, rk)
    return z


# ============================================================================== QuickSilver
def booleanity(B, w):
    one = B.const(1)
    return [B.lift(B.mul(wi, B.add(one, wi)), D_ZK - 2) for wi in w]


def zk_prove(P, wbits, V, ubar, vbar, chall2, relation):
    """relation(B, w) -> the relation constraints (degree-d_zk commitments).
    -> [a~_0 .. a~_{d_zk-1}]."""
    F = P.F
    B = ProverBackend(F)
    w = [[V[i], wbits[i]] for i in range(len(wbits))]
    z = booleanity(B, w) + relation(B, w)
    for c in z:
        if len(c) != D_ZK + 1:
            raise AssertionError("constraint is not of degree d_zk")
        if c[D_ZK]:
            raise ValueError("the witness does not satisfy the relation")
    at = []
    for j in range(D_ZK):
        if j == 0:
            pj = vbar[0]
        elif j == D_ZK - 1:
            pj = ubar[D_ZK - 2]
        else:
            pj = ubar[j - 1] ^ vbar[j]
        at.append(zk_hash(F, chall2, [c[j] for c in z], pj))
    return at, len(z)


def zk_verify(P, d, Q, qbar, chall2, delta, at_tail, relation):
    """-> a~_0."""
    F = P.F
    B = VerifierBackend(F, delta)
    w = [(Q[i] ^ (delta if (d >> i) & 1 else 0), 1) for i in range(len(Q))]
    z = booleanity(B, w) + relation(B, w)
    for c in z:
        if c[1] != D_ZK:
            raise AssertionError("constraint is not of degree d_zk")
    qstar = 0
    for j in range(D_ZK - 1):
        qstar ^= F.mul(qbar[j], B.dp[j])
    acc = zk_hash(F, chall2, [c[0] for c in z], qstar)
    for j in range(1, D_ZK):
        acc ^= F.mul(at_tail[j - 1], B.dp[j])
    return acc


# ============================================================================== FAEST
def int_to_bits(v, n):
    return [(v >> i) & 1 for i in range(n)]


def bits_to_int(bits):
    return int("".join("1" if b else "0" for b in reversed(bits)), 2) if bits else 0


def split_sk(P, sk):
    if len(sk) != P.sk_bytes:
        raise ValueError("secret key length")
    return sk[:P.x_bytes], sk[P.x_bytes:]


def public_key(P, sk):
    x, k = split_sk(P, sk)
    return x + owf(P, k, x)


def keygen(P, rand=os.urandom):
    while True:
        k = rand(P.lb)
        if (k[0] & 3) != 3:
            break
    x = rand(P.x_bytes)
    return x + k, x + owf(P, k, x)


def serialize_cm(P, cm):
    return b"".join(row.to_bytes(P.cm_row_bytes, "little") for row in cm)


def chall1_of(P, mu, com, cs, cm, iv_pre, salt=b""):
    ellb = P.ell // 8
    return H2(P.lam, 1, mu + com + b"".join(c.to_bytes(ellb, "little") for c in cs)
              + serialize_cm(P, cm) + iv_pre + salt, 8 * P.lb + 8, P.prefix)


def sign(P, sk, msg, rho=b"", trace=None):
    """-> signature bytes.  rho: signing randomness, absorbed by H3 exactly as given (no
    padding or truncation).  The specification (Fig. 8.2) defines rho in {0,1}^lambda and
    deterministic signing as rho = 0^lambda, i.e. pass bytes(P.lb).  The official vector
    generator passes 16 bytes for every lambda, which is why the bytes are absorbed unpadded.
    The default rho = b"" (nothing absorbed) is a convenience of this reference and is NOT
    the specification's deterministic mode.  `trace`, if a dict, receives the intermediate
    values."""
    lam, lb, ell, F = P.lam, P.lb, P.ell, P.F
    ellb = ell // 8
    x, k = split_sk(P, sk)
    pk = x + owf(P, k, x)
    mu = H2(lam, 0, pk + msg, 2 * lb, P.prefix)
    r, iv_pre = H3(lam, k + mu + rho)
    iv = H4(lam, iv_pre + mu, P.prefix)
    vc = vole_commit(P, r, iv)
    chall1 = chall1_of(P, mu, vc["com"], vc["cs"], vc["c_mult"], iv_pre)
    u, V, ubar, vbar = vc["u"], vc["V"], vc["ubar"], vc["vbar"]
    u_t = vole_hash(F, chall1, int_to_bits(u, ell) + ubar[:D_ZK - 1], ubar[D_ZK - 1:])
    v_t = vole_hash(F, chall1, V + vbar[:D_ZK - 1], vbar[D_ZK - 1:])
    wbits = extend_witness(P, k, x)
    d = bits_to_int(wbits) ^ u
    u_t_b = b"".join(F.to_bytes(e) for e in u_t)
    chall2 = H2(lam, 2, chall1 + u_t_b + b"".join(F.to_bytes(e) for e in v_t)
                + d.to_bytes(ellb, "little"), 3 * lb + 8, P.prefix)
    at, _ = zk_prove(P, wbits, V, ubar, vbar, chall2, lambda B, w: owf_constraints(B, P, w, pk))
    at_b = b"".join(F.to_bytes(e) for e in at)
    ctr = 0
    while True:
        chall3 = H2(lam, 3, chall2 + at_b + ctr.to_bytes(4, "little"), lb, P.prefix)
        idx = decode_all_chall3(P, int.from_bytes(chall3, "little"))
        if idx is not None:
            decom_i = bavc_open(P, vc["decom"], idx)
            if decom_i is not None:
                break
        if ctr == 0xFFFFFFFF:
            raise RuntimeError("grinding counter exhausted")
        ctr += 1
    if trace is not None:
        trace.update(mu=mu, r=r, iv_pre=iv_pre, iv=iv, com=vc["com"], chall1=chall1, u=u,
                     ubar=ubar, vbar=vbar, u_t=u_t, v_t=v_t, chall2=chall2, at=at, ctr=ctr,
                     chall3=chall3, idx=idx, V=V, wbits=wbits)
    return (b"".join(c.to_bytes(ellb, "little") for c in vc["cs"]) + serialize_cm(P, vc["c_mult"])
            + u_t_b + d.to_bytes(ellb, "little") + at_b[lb:] + decom_i + chall3 + iv_pre
            + ctr.to_bytes(4, "little"))


def parse_signature(P, sig):
    """-> dict of raw fields, or None if the length is wrong or a c_mult row has a
    non-zero bit at or above n_mult."""
    if len(sig) != P.sig_bytes:
        return None
    lb, ellb, rb = P.lb, P.ell // 8, P.cm_row_bytes
    f = {}
    off = 0

    def take(n):
        nonlocal off
        out = sig[off:off + n]
        off += n
        return out
    f["cs"] = [int.from_bytes(take(ellb), "little") for _ in range(P.tau - 1)]
    f["c_mult"] = [int.from_bytes(take(rb), "little") for _ in range(N_MASK)]
    f["u_t_b"] = take(4 * lb)
    f["d"] = int.from_bytes(take(ellb), "little")
    f["at_tail"] = [int.from_bytes(take(lb), "little") for _ in range(D_ZK - 1)]
    f["decom_i"] = take(P.tau * P.leaf_bytes + P.t_open * lb)
    f["chall3"] = take(lb)
    f["iv_pre"] = take(16)
    f["salt"] = take(32) if P.extended else b""
    f["ctr"] = take(4)
    if P.extended and int.from_bytes(f["ctr"], "little") >= 1 << 20:
        return None
    assert off == len(sig)
    if any(row >> P.n_mult for row in f["c_mult"]):
        return None
    return f


def verify(P, pk, msg, sig, cache=None, trace=None):
    lam, lb, ell, F = P.lam, P.lb, P.ell, P.F
    ellb = ell // 8
    if len(pk) != P.pk_bytes:
        return False
    f = parse_signature(P, sig)
    if f is None:
        return False
    mu = H2(lam, 0, pk + msg, 2 * lb, P.prefix)
    iv = H4(lam, f["iv_pre"] + mu, P.prefix)
    chall = int.from_bytes(f["chall3"], "little")
    if chall >> P.nd:
        return False
    rec = vole_reconstruct(P, chall, f["decom_i"], f["cs"], f["c_mult"], iv, cache=cache)
    if rec is None:
        return False
    Q, qbar, delta = rec["Q"], rec["qbar"], rec["delta"]
    chall1 = chall1_of(P, mu, rec["com"], f["cs"], f["c_mult"], f["iv_pre"])
    q_t = vole_hash(F, chall1, Q + qbar[:D_ZK - 1], qbar[D_ZK - 1:])
    u_t = [int.from_bytes(f["u_t_b"][i * lb:(i + 1) * lb], "little") for i in range(4)]
    dd = [q_t[i] ^ F.mul(delta, u_t[i]) for i in range(4)]
    chall2 = H2(lam, 2, chall1 + f["u_t_b"] + b"".join(F.to_bytes(e) for e in dd)
                + f["d"].to_bytes(ellb, "little"), 3 * lb + 8, P.prefix)
    a0 = zk_verify(P, f["d"], Q, qbar, chall2, delta, f["at_tail"],
                   lambda B, w: owf_constraints(B, P, w, pk))
    at_b = F.to_bytes(a0) + b"".join(F.to_bytes(e) for e in f["at_tail"])
    chall3 = H2(lam, 3, chall2 + at_b + f["ctr"], lb, P.prefix)
    if trace is not None:
        trace.update(mu=mu, iv=iv, com=rec["com"], chall1=chall1, chall2=chall2, a0=a0,
                     delta=delta, dd=dd, chall3=chall3)
    return chall3 == f["chall3"]
