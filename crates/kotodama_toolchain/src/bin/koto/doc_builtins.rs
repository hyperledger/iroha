//! Generated source-visible builtin reference for `koto doc --builtins`.
use kotodama_lang::{
    glossary::BRANDED_KEYWORDS,
    signature_render::{RenderParameter, access_words, builtin_documentation, parameter_list},
};
use kotodama_surface::{
    builtin_docs::builtin_doc,
    builtins::{Builtin, BuiltinMode, BuiltinSpec, BuiltinSurface},
};
use norito::json::{Value, object};

fn registry() -> Vec<(Builtin, BuiltinSpec)> {
    let mut entries = Builtin::registry()
        .filter(|(_, spec)| {
            spec.surface != BuiltinSurface::CompilerInternal
                && spec.mode != BuiltinMode::CompilerInternal
        })
        .collect::<Vec<_>>();
    entries.sort_by_key(|(_, spec)| spec.name);
    entries
}

fn availability(mode: BuiltinMode) -> &'static str {
    match mode {
        BuiltinMode::Any => "production",
        BuiltinMode::ZkOnly => "zk",
        BuiltinMode::TestOnly => "test_build",
        BuiltinMode::TestFunctionOnly => "test_function",
        BuiltinMode::CompilerInternal => unreachable!("internal builtins are not documented"),
    }
}

fn surface(builtin: Builtin) -> &'static str {
    if builtin.is_nominal_path() {
        return "value";
    }
    match builtin.surface() {
        BuiltinSurface::Function => "function",
        BuiltinSurface::MethodOnly => "method",
        BuiltinSurface::FunctionOrMethod => "function_or_method",
        BuiltinSurface::CompilerInternal => unreachable!("internal builtins are not documented"),
    }
}

fn signature(builtin: Builtin, spec: &BuiltinSpec) -> String {
    if builtin.is_nominal_path() {
        return format!("{}: {}", spec.name, spec.signature.return_type);
    }
    let method = spec.surface == BuiltinSurface::MethodOnly;
    let parameters = spec
        .signature
        .parameter_names
        .iter()
        .zip(spec.signature.parameters)
        .enumerate()
        .skip(usize::from(method))
        .map(|(index, (name, ty))| RenderParameter {
            name,
            ty,
            named: spec.call_policy.label_required(index),
        })
        .collect::<Vec<_>>();
    let receiver = if method {
        format!("{}.", spec.signature.parameters[0])
    } else {
        String::new()
    };
    format!(
        "{receiver}{}({}) -> {}",
        spec.name,
        parameter_list(&parameters),
        spec.signature.return_type
    )
}

pub(super) fn markdown() -> String {
    let mut text = String::from(
        "# Kotodama builtin reference\n\n\
         Generated by `koto doc --builtins` from the compiler's builtin registry and authored summaries. \
         Entries use their canonical source paths; receiver methods are marked with their receiver type. \
         Compiler-internal operations are omitted.\n\n\
         Signatures below describe types and labels rather than complete programs. A parameter marked `_` \
         accepts either positional or named arguments; other parameters require their names (label punning \
         is accepted). In registry type descriptors, `A|B` is a closed union, a trailing `?` is an optional \
         final parameter, and `...` is a variadic tail. Generic names describe relationships between \
         argument and result types.\n\n\
         Production, ZK, local-test-build and test-function APIs are included together; each restricted \
         entry states its required capability. Availability does not bypass the entry's effects or \
         authorization requirements.\n\n## Declaration terminology\n\n",
    );
    for keyword in BRANDED_KEYWORDS {
        text.push_str(&format!(
            "- `{}` / `{}`: {}.\n",
            keyword.romaji, keyword.kanji, keyword.role
        ));
    }
    text.push_str("\nBoth spellings are the same keyword and may be mixed freely.\n");
    for (builtin, spec) in registry() {
        text.push_str(&format!(
            "\n## `{}`\n\n```text\n{}\n```\n\n{}\n",
            spec.name,
            signature(builtin, &spec),
            builtin_documentation(builtin)
        ));
        if builtin.is_compile_time_nominal() {
            text.push_str("\nThis compile-time value is accepted only by parameters of its declared nominal type.\n");
        }
    }
    text
}

pub(super) fn json() -> Result<Value, String> {
    let entries = registry()
        .into_iter()
        .map(|(builtin, spec)| {
            let method = spec.surface == BuiltinSurface::MethodOnly;
            let parameters = spec
                .signature
                .parameter_names
                .iter()
                .zip(spec.signature.parameters)
                .enumerate()
                .map(|(index, (name, ty))| {
                    object([
                        ("name", Value::from(*name)),
                        ("type", Value::from(*ty)),
                        ("receiver", Value::from(method && index == 0)),
                        (
                            "label_required",
                            Value::from(
                                !(method && index == 0) && spec.call_policy.label_required(index),
                            ),
                        ),
                    ])
                })
                .collect::<Result<Vec<_>, _>>()
                .map_err(|error| error.to_string())?;
            object([
                ("source_path", Value::from(spec.name)),
                ("surface", Value::from(surface(builtin))),
                ("availability", Value::from(availability(spec.mode))),
                (
                    "compile_time",
                    Value::from(builtin.is_compile_time_nominal()),
                ),
                ("signature", Value::from(signature(builtin, &spec))),
                ("parameters", Value::Array(parameters)),
                ("return_type", Value::from(spec.signature.return_type)),
                (
                    "summary",
                    Value::from(builtin_doc(spec.name).ok_or_else(|| {
                        format!(
                            "source-visible builtin `{}` has no authored summary",
                            spec.name
                        )
                    })?),
                ),
                ("documentation", Value::from(builtin_documentation(builtin))),
                ("access", Value::from(access_words(spec.access))),
                (
                    "effects",
                    object([
                        (
                            "host_side_effects",
                            Value::from(spec.effects.host_side_effects),
                        ),
                        (
                            "emits_instructions",
                            Value::from(spec.effects.emits_instructions),
                        ),
                        (
                            "mutates_durable_state",
                            Value::from(spec.effects.mutates_durable_state),
                        ),
                    ])
                    .map_err(|error| error.to_string())?,
                ),
            ])
            .map_err(|error| error.to_string())
        })
        .collect::<Result<Vec<_>, _>>()?;
    let terminology = BRANDED_KEYWORDS
        .iter()
        .map(|keyword| {
            object([
                ("romaji", Value::from(keyword.romaji)),
                ("kanji", Value::from(keyword.kanji)),
                ("role", Value::from(keyword.role)),
            ])
        })
        .collect::<Result<Vec<_>, _>>()
        .map_err(|error| error.to_string())?;
    object([
        ("builtins", Value::Array(entries)),
        ("declaration_keywords", Value::Array(terminology)),
    ])
    .map_err(|error| error.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reference_is_exhaustive_sorted_and_uses_authored_documentation() {
        let records = json().expect("complete authored builtin documentation");
        let entries = records["builtins"].as_array().expect("builtin records");
        let expected = registry();
        assert_eq!(entries.len(), expected.len());
        assert!(!entries.is_empty());
        let rendered = markdown();
        for ((builtin, spec), entry) in expected.iter().zip(entries) {
            assert_eq!(entry["source_path"].as_str(), Some(spec.name));
            assert_eq!(
                entry["return_type"].as_str(),
                Some(spec.signature.return_type)
            );
            assert_eq!(entry["summary"].as_str(), builtin_doc(spec.name));
            assert!(!entry["summary"].as_str().unwrap().trim().is_empty());
            assert_eq!(
                entry["parameters"].as_array().unwrap().len(),
                spec.signature.parameters.len()
            );
            assert!(rendered.contains(&format!("\n## `{}`\n", spec.name)));
            assert!(rendered.contains(&builtin_documentation(*builtin)));
        }
        for keyword in BRANDED_KEYWORDS {
            assert!(rendered.contains(&format!("`{}` / `{}`", keyword.romaji, keyword.kanji)));
        }
        assert_eq!(markdown(), rendered);
        assert!(!rendered.contains("BuiltinEffects") && !rendered.contains("CompilerInternal"));
    }

    #[test]
    fn reference_keeps_labels_receiver_forms_types_and_capabilities() {
        let records = json().unwrap();
        let entries = records["builtins"].as_array().unwrap();
        let find = |name: &str| {
            entries
                .iter()
                .find(|entry| entry["source_path"].as_str() == Some(name))
                .unwrap()
        };
        let transfer = find("ledger::asset::transfer");
        assert!(
            transfer["parameters"]
                .as_array()
                .unwrap()
                .iter()
                .all(|parameter| parameter["label_required"].as_bool() == Some(true))
        );
        assert_eq!(
            transfer["effects"]["host_side_effects"].as_bool(),
            Some(true)
        );
        let contains = find("contains");
        assert_eq!(contains["surface"].as_str(), Some("method"));
        assert_eq!(contains["parameters"][0]["receiver"].as_bool(), Some(true));
        assert_eq!(
            contains["signature"].as_str(),
            Some("StateMap<K,V>.contains(K _ key) -> bool")
        );
        assert_eq!(
            find("Mintable::Once")["signature"].as_str(),
            Some("Mintable::Once: Mintable")
        );
        assert_eq!(
            find("NumericSpec::integer")["signature"].as_str(),
            Some("NumericSpec::integer() -> NumericSpec")
        );
        assert_eq!(
            find("test::invoke_kotoage")["availability"].as_str(),
            Some("test_function")
        );
        let private_input = find("crypto::private_input");
        assert_eq!(private_input["availability"].as_str(), Some("zk"));
        let private_summary = private_input["summary"].as_str().unwrap();
        assert!(private_summary.contains("prover or local test host"));
        assert!(private_summary.contains("Production consensus hosts never provide"));
        assert!(
            find("test::invoke_kotoage")["documentation"]
                .as_str()
                .unwrap()
                .contains("inside `#[test]`")
        );
        for (builtin, spec) in Builtin::registry() {
            if spec.surface == BuiltinSurface::CompilerInternal
                || spec.mode == BuiltinMode::CompilerInternal
            {
                assert!(
                    !entries
                        .iter()
                        .any(|entry| entry["source_path"].as_str() == Some(spec.name)),
                    "{builtin:?}"
                );
            } else if spec.mode == BuiltinMode::ZkOnly {
                assert_eq!(find(spec.name)["availability"].as_str(), Some("zk"));
                assert!(
                    find(spec.name)["documentation"]
                        .as_str()
                        .unwrap()
                        .contains("ZK compilation")
                );
            }
        }
    }
}
