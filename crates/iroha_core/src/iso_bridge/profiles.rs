const MAX_PROFILE_DER_BYTES: usize = 1024 * 1024;
const OCSP_BASIC_RESPONSE_OID_DER: &[u8] = &[0x2b, 0x06, 0x01, 0x05, 0x05, 0x07, 0x30, 0x01, 0x01];
