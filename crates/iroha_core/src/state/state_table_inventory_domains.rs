//! Exact classification of every domain literal that the State inventory scan discovers
//! and that is not a commitment over State content.
//!
//! Each literal is listed as written in the source (escapes are not interpreted). No entry
//! matches a prefix: a new literal fails `state_table_inventory_tests` until it is listed
//! here with its use, or under a commitment in `ROOTS` or an application accumulator.

/// What a domain literal is used for when it is not a commitment over State content.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Use {
    /// Domain tag of the execution result, the certified block identity or a lane result.
    ResultBinding,
    /// Key of an execution-witness family.
    WitnessKey,
    /// Commitment over a block's or a transaction's own content.
    BlockContent,
    /// Identifier, content hash, statement or signing preimage of one record or message.
    Record,
    /// Expected-value hash of one State value named by a transaction or a State record.
    Precondition,
    /// Sampling seed or derived identifier.
    Seed,
    /// Schema, wire, backend, parameter or storage-key name: not a hash domain.
    Name,
    /// Binding of a node-local artifact that holds no State content.
    LocalArtifact,
    /// Test input or fixture.
    Test,
}

impl Use {
    /// The name of the use in the inventory.
    pub(super) const fn name(self) -> &'static str {
        match self {
            Self::ResultBinding => "result_binding",
            Self::WitnessKey => "witness_key",
            Self::BlockContent => "block_content",
            Self::Record => "record",
            Self::Precondition => "precondition",
            Self::Seed => "seed",
            Self::Name => "name",
            Self::LocalArtifact => "local_artifact",
            Self::Test => "test",
        }
    }
}

