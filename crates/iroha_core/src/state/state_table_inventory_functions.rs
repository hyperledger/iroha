//! Exact classification of every `iroha_core` function that the State inventory scan
//! finds by its signature: a function or method with a State or World receiver or reader
//! argument and a hash-bearing return value. A reader is `State`, `World` or the owner of
//! another registry field (the transaction storage, the block-hash journal, the trigger
//! set, the canonical runtime) with its handles and reader traits, or a table or cell
//! handle.
//!
//! Each entry names the source, the function and the number of matching functions of that
//! name in the source. A new, renamed or moved match fails `state_table_inventory_tests`
//! until it is listed here under the commitment it computes or serves, under an
//! application accumulator, or with its reviewed use.

use super::{UseOwner, domains::Use};

/// One function that reads State and returns a hash-bearing value, and what owns it.
pub(super) struct StateHashFunction {
    pub(super) path: &'static str,
    pub(super) name: &'static str,
    /// Number of matching functions of this name in the source.
    pub(super) count: usize,
    pub(super) owner: UseOwner,
}

const BLOCK_HASH: &str = "Reads committed block hashes or the hash of the current block header: authenticated history and block identity, not a digest of State content";
const RECORD_IDENTITY: &str = "Returns the identifier, content hash or stored digest of one record, transaction or message: no digest over a table or cell";
const DERIVED_SEED: &str =
    "Derives a sampling seed or an identifier from committed records or from the current block";
const EXPECTED_VALUE: &str = "Canonical hash of one State value (the protected runtime catalog parameter) that a lane lifecycle transaction names as its expected value and that the status endpoint serves";
const TEST_ONLY: &str =
    "Table accessors and fixtures compiled for tests or under a test-only feature";
const CERTIFIED_IDENTITY: &str = "Carries the certified block identity and R of a committed height (the execution tip or a finality proof): it binds the listed roots and digests no State content of its own";
const BLOCK_PROOF: &str =
    "Merkle proofs of a transaction entrypoint and its result inside their block: block content";
const TABLE_ACCESSOR: &str = "Borrows a table whose key type is the content hash of one record (a pin manifest, contract bytecode): a table accessor that computes no digest";

const fn function(
    path: &'static str,
    name: &'static str,
    count: usize,
    owner: UseOwner,
) -> StateHashFunction {
    StateHashFunction {
        path,
        name,
        count,
        owner,
    }
}

