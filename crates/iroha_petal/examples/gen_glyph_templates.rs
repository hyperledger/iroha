//! Prints `src/glyph_templates.rs` from the stroke definitions.
use iroha_petal::glyphs::{GLYPH_CHARS, GLYPH_COUNT, TEMPLATE_N, generate_templates};

fn main() {
    let templates = generate_templates();
    println!("// @generated by `cargo run -p iroha_petal --example gen_glyph_templates`.");
    println!("// Do not edit: `glyphs::tests` regenerates and compares this table.");
    println!("/// Area-coverage templates (`0..=255`) of the glyph alphabet, row-major `8 x 8`.");
    println!("pub static TEMPLATES: [[u8; TEMPLATE_N * TEMPLATE_N]; GLYPH_COUNT] = [");
    for glyph in 0..GLYPH_COUNT {
        println!("    // {}", GLYPH_CHARS[glyph]);
        println!("    [");
        for row in 0..TEMPLATE_N {
            let cells: Vec<String> = (0..TEMPLATE_N)
                .map(|col| format!("{:3}", templates[glyph][row * TEMPLATE_N + col]))
                .collect();
            println!("        {},", cells.join(", "));
        }
        println!("    ],");
    }
    println!("];");
}
