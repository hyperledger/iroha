//! Deterministic workloads of the candidate measurements.
//!
//! A workload is a pure function of its parameters: the same seed yields the
//! same keys, values and change sets on every machine, so two runs measure the
//! same work and a tracked figure can be reproduced. The populations are
//! declared experimental assumptions, not State bounds: the State inventory
//! names the tables and codecs but states no population.
//!
//! TODO(G.3): delete with the prototypes.

use super::keyed::{PrototypeSchema, TableChange, descriptor_from_rows};

/// The canonical schema descriptor that the tracked State inventory
/// (`specs/state_table_inventory.json`) declares: one row per `canonical`
/// field, a table with its key and value codec identities or a cell with its
/// value codec identity.
///
/// `iroha_core` checks that the result equals the descriptor of the authority
/// registry, so a measurement over it is a measurement over the real schema.
/// Returns `None` when the text is not an inventory of that form.
#[must_use]
pub fn descriptor_from_inventory(inventory_json: &str) -> Option<Vec<u8>> {
    let inventory = norito::json::parse_value(inventory_json).ok()?;
    let mut rows = Vec::new();
    for field in inventory.get("fields")?.as_array()? {
        if field.get("role")?.as_str()? != "canonical" {
            continue;
        }
        let key = match field.get("shape")?.as_str()? {
            "table" => field.get("key")?.as_str()?,
            "cell" => "",
            _ => return None,
        };
        rows.push((
            field.get("id")?.as_str()?,
            key,
            field.get("value")?.as_str()?,
        ));
    }
    Some(descriptor_from_rows(&rows))
}

/// `SplitMix64`: a small deterministic generator, good enough for workloads.
#[derive(Clone, Copy, Debug)]
pub struct SplitMix64(u64);

impl SplitMix64 {
    /// A generator from a seed.
    #[must_use]
    pub const fn new(seed: u64) -> Self {
        Self(seed)
    }

    /// The next 64 bits.
    pub fn next_u64(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9e37_79b9_7f4a_7c15);
        let mut mixed = self.0;
        mixed = (mixed ^ (mixed >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
        mixed = (mixed ^ (mixed >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
        mixed ^ (mixed >> 31)
    }

    /// A value below `bound`; `bound` must be positive.
    pub fn below(&mut self, bound: u64) -> u64 {
        self.next_u64() % bound
    }

    /// Fill a buffer with generated bytes.
    pub fn fill(&mut self, bytes: &mut [u8]) {
        for chunk in bytes.chunks_mut(8) {
            let word = self.next_u64().to_le_bytes();
            chunk.copy_from_slice(&word[..chunk.len()]);
        }
    }
}

/// Shape of the keys of the populated table.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum KeyShape {
    /// 32 scattered bytes, like a hash or an account identifier.
    Scattered32,
    /// 32 bytes: a fixed 24-byte prefix and an 8-byte big-endian counter, like
    /// a framed tuple key whose leading components are shared.
    SharedPrefix32,
    /// 128 bytes: a fixed 96-byte prefix and 32 scattered bytes.
    Long128,
}

impl KeyShape {
    /// Stable name recorded with a measurement.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            Self::Scattered32 => "scattered-32",
            Self::SharedPrefix32 => "shared-prefix-32",
            Self::Long128 => "long-128",
        }
    }

    /// Key length in bytes.
    #[must_use]
    pub const fn bytes(self) -> usize {
        match self {
            Self::Scattered32 | Self::SharedPrefix32 => 32,
            Self::Long128 => 128,
        }
    }
}

/// Entries of every keyed table other than the populated one.
pub const BACKGROUND_ENTRIES: u64 = 4;

/// One declared experimental State population.
///
/// The populated table holds `population` entries with keys of `key_shape`.
/// Every cell holds its one entry and every other table holds
/// [`BACKGROUND_ENTRIES`] entries, so the commitment always spans the whole
/// schema.
#[derive(Clone, Debug)]
pub struct StateWorkload {
    seed: u64,
    cells: Vec<bool>,
    populated: u32,
    population: u64,
    key_shape: KeyShape,
    value_bytes: usize,
}

/// One owned change: table position, key and the value after the change.
pub type OwnedChange = (u32, Vec<u8>, Option<Vec<u8>>);

impl StateWorkload {
    /// A workload over `schema` whose table at position `populated` holds
    /// `population` entries.
    ///
    /// # Panics
    /// Panics when `populated` is not a keyed table of the schema.
    #[must_use]
    pub fn new(
        schema: &PrototypeSchema,
        populated: u32,
        population: u64,
        key_shape: KeyShape,
        value_bytes: usize,
        seed: u64,
    ) -> Self {
        let cells: Vec<bool> = (0..schema.tables())
            .map(|table| schema.is_cell(table).expect("a declared position"))
            .collect();
        assert_eq!(
            cells.get(populated as usize),
            Some(&false),
            "the populated position is a keyed table"
        );
        Self {
            seed,
            cells,
            populated,
            population,
            key_shape,
            value_bytes,
        }
    }

    /// Position of the populated table.
    #[must_use]
    pub const fn populated(&self) -> u32 {
        self.populated
    }

    /// Entries of the populated table.
    #[must_use]
    pub const fn population(&self) -> u64 {
        self.population
    }

    fn generator(&self, table: u32, index: u64, stream: u64) -> SplitMix64 {
        let mut mixer = SplitMix64::new(self.seed ^ stream.wrapping_mul(0xa24b_aed4_963e_e407));
        let table_word = mixer.next_u64() ^ u64::from(table);
        let mut generator = SplitMix64::new(table_word.wrapping_mul(0x9fb2_1c65_1e98_df25) ^ index);
        generator.next_u64();
        generator
    }

    /// Key `index` of a table. Indices at or above the population are keys
    /// that are never committed by [`Self::initial`].
    #[must_use]
    pub fn key(&self, table: u32, index: u64) -> Vec<u8> {
        if self.cells[table as usize] {
            return Vec::new();
        }
        let shape = if table == self.populated {
            self.key_shape
        } else {
            KeyShape::Scattered32
        };
        let mut key = vec![0_u8; shape.bytes()];
        let mut generator = self.generator(table, index, 1);
        match shape {
            KeyShape::Scattered32 => generator.fill(&mut key),
            KeyShape::SharedPrefix32 => {
                key[..24].fill(0xa5);
                // A bijection of the index keeps the keys distinct and unordered.
                key[24..].copy_from_slice(&index.wrapping_mul(0x9e37_79b9_7f4a_7c15).to_be_bytes());
            }
            KeyShape::Long128 => {
                key[..96].fill(0x5a);
                generator.fill(&mut key[96..]);
            }
        }
        key
    }

    /// Value of entry `index` of a table at one version.
    #[must_use]
    pub fn value(&self, table: u32, index: u64, version: u64) -> Vec<u8> {
        let mut value = vec![0_u8; self.value_bytes];
        self.generator(table, index, 2 + version).fill(&mut value);
        value
    }

    /// Entries the table at `table` holds initially.
    #[must_use]
    pub fn table_entries(&self, table: u32) -> u64 {
        if self.cells[table as usize] {
            1
        } else if table == self.populated {
            self.population
        } else {
            BACKGROUND_ENTRIES
        }
    }

    /// Every entry of the initial State, as one change set.
    #[must_use]
    pub fn initial(&self) -> Vec<OwnedChange> {
        let mut changes = Vec::new();
        for (table, _) in (0_u32..).zip(&self.cells) {
            for index in 0..self.table_entries(table) {
                changes.push((
                    table,
                    self.key(table, index),
                    Some(self.value(table, index, 0)),
                ));
            }
        }
        changes
    }

    /// Change set `round` of `size` changes over several tables.
    ///
    /// Of every ten changes, seven rewrite an entry of the populated table,
    /// one inserts a new key there, one removes one of its initial entries and
    /// one rewrites an entry of another table or a cell. No position occurs
    /// twice in one set.
    #[must_use]
    pub fn change_set(&self, round: u64, size: usize) -> Vec<OwnedChange> {
        let mut generator = SplitMix64::new(self.seed ^ round.wrapping_mul(0xd6e8_feb8_6659_fd93));
        let mut seen = std::collections::BTreeSet::new();
        let mut changes = Vec::with_capacity(size);
        let tables = self.cells.len() as u64;
        while changes.len() < size {
            let kind = changes.len() % 10;
            let (table, index, value) = match kind {
                7 => {
                    let index = self.population + (round << 32) + changes.len() as u64;
                    (self.populated, index, Some(round + 1))
                }
                8 => (
                    self.populated,
                    generator.below(self.population.max(1)),
                    None,
                ),
                9 if tables > 1 => {
                    let table = u32::try_from(generator.below(tables))
                        .expect("a position below the table count");
                    let index = generator.below(self.table_entries(table).max(1));
                    (table, index, Some(round + 1))
                }
                _ => (
                    self.populated,
                    generator.below(self.population.max(1)),
                    Some(round + 1),
                ),
            };
            if !seen.insert((table, index)) {
                continue;
            }
            changes.push((
                table,
                self.key(table, index),
                value.map(|version| self.value(table, index, version)),
            ));
        }
        changes
    }
}

/// Borrow owned changes in the form [`super::KeyedMap::apply`] takes.
#[must_use]
pub fn borrow_changes(changes: &[OwnedChange]) -> Vec<TableChange<'_>> {
    changes
        .iter()
        .map(|(table, key, value)| (*table, key.as_slice(), value.as_deref()))
        .collect()
}

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;
    use crate::state_commitment_prototypes::keyed::descriptor_from_rows;

    fn schema() -> PrototypeSchema {
        PrototypeSchema::from_descriptor(&descriptor_from_rows(&[
            ("w.accounts", "norito:K@0.0.2", "norito:V@0.0.2"),
            ("w.assets", "norito:K@0.0.2", "norito:V@0.0.2"),
            ("w.params", "", "norito:P@0.0.2"),
        ]))
        .expect("a canonical descriptor")
    }

    #[test]
    fn inventory_rows_become_the_canonical_descriptor() {
        let inventory = r#"{"fields": [
            {"id": "state.world", "role": "owner"},
            {"id": "w.b", "role": "canonical", "shape": "table", "key": "norito:K@0.0.2", "value": "norito:V@0.0.2"},
            {"id": "w.index", "role": "derived"},
            {"id": "w.a", "role": "canonical", "shape": "cell", "value": "semantic:C@0.0.2"}
        ]}"#;
        let descriptor = descriptor_from_inventory(inventory).unwrap();
        assert_eq!(
            descriptor,
            descriptor_from_rows(&[
                ("w.a", "", "semantic:C@0.0.2"),
                ("w.b", "norito:K@0.0.2", "norito:V@0.0.2"),
            ])
        );
        let schema = PrototypeSchema::from_descriptor(&descriptor).unwrap();
        assert_eq!(schema.tables(), 2);
        assert_eq!(schema.is_cell(0), Some(true));
        assert_eq!(schema.identity(1), Some("w.b"));
        assert!(descriptor_from_inventory("{}").is_none());
        assert!(descriptor_from_inventory("not json").is_none());
        assert!(
            descriptor_from_inventory(
                r#"{"fields": [{"id": "x", "role": "canonical", "shape": "heap", "value": "v"}]}"#
            )
            .is_none()
        );
    }

    #[test]
    fn generator_is_deterministic_and_fills_exactly() {
        let (mut left, mut right) = (SplitMix64::new(7), SplitMix64::new(7));
        assert_eq!(left.next_u64(), right.next_u64());
        // The first output of SplitMix64 for seed 0 is a published constant.
        assert_eq!(SplitMix64::new(0).next_u64(), 0xe220_a839_7b1d_cdaf);
        assert!((0..100).all(|_| left.below(5) < 5));
        let mut bytes = [0_u8; 11];
        right.fill(&mut bytes);
        assert_ne!(bytes, [0; 11]);
    }

    #[test]
    fn workload_keys_are_distinct_and_have_their_declared_shape() {
        let schema = schema();
        let accounts = schema.position("w.accounts").unwrap();
        for shape in [
            KeyShape::Scattered32,
            KeyShape::SharedPrefix32,
            KeyShape::Long128,
        ] {
            let workload = StateWorkload::new(&schema, accounts, 500, shape, 48, 11);
            let keys: BTreeSet<Vec<u8>> = (0..600)
                .map(|index| workload.key(accounts, index))
                .collect();
            assert_eq!(keys.len(), 600, "{}", shape.name());
            assert!(keys.iter().all(|key| key.len() == shape.bytes()));
            if shape != KeyShape::Scattered32 {
                let prefix = shape.bytes() * 3 / 4;
                let first = keys.iter().next().unwrap();
                assert!(keys.iter().all(|key| key[..prefix] == first[..prefix]));
            }
            assert_eq!(workload.value(accounts, 3, 0).len(), 48);
            assert_ne!(
                workload.value(accounts, 3, 0),
                workload.value(accounts, 3, 1)
            );
            assert_eq!(
                workload.value(accounts, 3, 1),
                workload.value(accounts, 3, 1)
            );
            assert_eq!(workload.populated(), accounts);
            assert_eq!(workload.population(), 500);
        }
    }

    #[test]
    fn initial_state_spans_every_table_and_cell() {
        let schema = schema();
        let accounts = schema.position("w.accounts").unwrap();
        let cell = schema.position("w.params").unwrap();
        let workload = StateWorkload::new(&schema, accounts, 40, KeyShape::Scattered32, 32, 1);
        let initial = workload.initial();
        assert_eq!(initial.len() as u64, 40 + BACKGROUND_ENTRIES + 1);
        assert_eq!(workload.table_entries(cell), 1);
        assert!(
            initial
                .iter()
                .any(|(table, key, _)| *table == cell && key.is_empty())
        );
        let positions: BTreeSet<(u32, &[u8])> = initial
            .iter()
            .map(|(table, key, _)| (*table, key.as_slice()))
            .collect();
        assert_eq!(positions.len(), initial.len());
        assert_eq!(borrow_changes(&initial).len(), initial.len());
    }

    #[test]
    fn change_sets_touch_several_tables_without_repeating_a_position() {
        let schema = schema();
        let accounts = schema.position("w.accounts").unwrap();
        let workload = StateWorkload::new(&schema, accounts, 1_000, KeyShape::Scattered32, 32, 5);
        let changes = workload.change_set(3, 200);
        assert_eq!(changes.len(), 200);
        assert_eq!(changes, workload.change_set(3, 200));
        assert_ne!(changes, workload.change_set(4, 200));
        let positions: BTreeSet<(u32, &[u8])> = changes
            .iter()
            .map(|(table, key, _)| (*table, key.as_slice()))
            .collect();
        assert_eq!(positions.len(), 200);
        assert!(changes.iter().any(|(_, _, value)| value.is_none()));
        assert!(changes.iter().any(|(table, _, _)| *table != accounts));
        // An inserted key is not one of the initial keys.
        let initial: BTreeSet<Vec<u8>> = (0..1_000)
            .map(|index| workload.key(accounts, index))
            .collect();
        assert!(changes.iter().any(|(table, key, value)| *table == accounts
            && value.is_some()
            && !initial.contains(key)));
    }
}
