//! Scalar slot encodings: the sparse subalgebra and fully split batching.
//!
//! Let `S` be the largest power of two with `t = 1 (mod 2S)` and `S <= N`,
//! and `zeta` a primitive `2S`-th root of unity modulo `t`. With
//! `Y = X^(N/S)`, `X^N + 1 = prod_j (Y - beta_j)` modulo `t` for
//! `beta_j = zeta^(2j+1)`, `0 <= j < S`. A vector of `S` scalars `v_j` is the
//! polynomial `g(Y)` of degree below `S` with `g(beta_j) = v_j`; only the
//! coefficients at multiples of `N/S` can be non-zero. Addition and
//! multiplication of such polynomials act slot by slot.
//!
//! - `S = N` is ordinary fully split batching (`t = 1 mod 2N`).
//! - `S < N` is the sparse scalar subalgebra: each factor `Y - beta_j` is a
//!   polynomial of degree `N/S` in `X` whose residue ring is an extension of
//!   the prime field (a field when the factor is irreducible, as for
//!   `t = 257`), and the encoding uses its constants only. For `t = 257`,
//!   `S = 128` at every `N >= 128` and `zeta = 3`.
//!
//! A plaintext outside the scalar subalgebra is a valid ring element but not
//! a slot vector, and slot-wise identities such as `x^(t-1) = 1` for non-zero
//! `x` do not hold for it. [`SlotEncoding::decode`] rejects one; an evaluator
//! that cannot see the plaintext needs a proof of membership from whoever
//! encrypted it.
//!
//! # Movement and masks
//!
//! `X -> X^a` maps slot `j` of the result to slot `pi(j)` of the argument with
//! `2*pi(j) + 1 = a*(2j + 1) (mod 2S)` ([`SlotEncoding::slot_source`]). The
//! unit group modulo `2S` is generated by 5 and -1, so one selected slot is
//! broadcast to all `S` slots by `log2(S)` steps `x <- x + x(X^g)` with
//! `g = 5^(2^i)` for `i < log2(S) - 1` and then `g = -1`
//! ([`SlotEncoding::broadcast_elements`]).
//!
//! The idempotent `e_j` (one in slot `j`, zero elsewhere) has coefficients
//! `S^-1 * beta_j^-k`. Its centered `l1` norm is the same for every `j`
//! because every `beta_j^-1` generates the same group of order `2S`;
//! [`SlotEncoding::mask_bound`] is that exact value and is public.
use super::{BgvError, BgvProfile, Ciphertext, EvaluationKeys, Plaintext, PlaintextBound};
use crate::{
    constant_time::{FixedModulus, greater_than_bit_u64, select_u64},
    modular,
    ntt::{forward_negacyclic_ntt_with, inverse_negacyclic_ntt_with},
};
use zeroize::Zeroizing;

/// Largest generator tried when the slot root is derived.
const ROOT_CANDIDATE_LIMIT: u64 = 1 << 16;

/// The scalar slot encoding of one profile.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SlotEncoding {
    identity: [u8; 32],
    degree: usize,
    slots: usize,
    plaintext: FixedModulus,
    root: u64,
    inverse_root: u64,
    inverse_slots: u64,
    mask_l1: u64,
}

impl SlotEncoding {
    /// Derive the encoding of a profile.
    ///
    /// The root is `g^((t - 1) / 2S)` for the smallest `g >= 2` that makes it a
    /// primitive `2S`-th root of unity; for `t = 257` that is 3.
    ///
    /// # Errors
    /// [`BgvError::EncodingUnavailable`] when `t = 3 (mod 4)`, so that no two
    /// slots exist.
    pub fn new(profile: &BgvProfile) -> Result<Self, BgvError> {
        let plaintext_modulus = profile.plaintext_modulus();
        let degree = profile.degree();
        // The largest power of two dividing (t - 1) / 2, capped by the ring degree.
        let two_adic = ((plaintext_modulus - 1) / 2).trailing_zeros().min(63);
        let slots = (1_usize << two_adic.min(usize::BITS - 2)).min(degree);
        if slots < 2 {
            return Err(BgvError::EncodingUnavailable);
        }
        let order = u64::try_from(2 * slots).map_err(|_| BgvError::EncodingUnavailable)?;
        let root = modular::primitive_root_of_order_with_candidate_limit(
            plaintext_modulus,
            order,
            ROOT_CANDIDATE_LIMIT,
        )
        .ok_or(BgvError::EncodingUnavailable)?;
        let inverse_root = modular::mod_inv_prime_u64(root, plaintext_modulus)
            .ok_or(BgvError::EncodingUnavailable)?;
        let inverse_slots = modular::mod_inv_prime_u64(order / 2, plaintext_modulus)
            .ok_or(BgvError::EncodingUnavailable)?;
        let mut encoding = Self {
            identity: *profile.identity(),
            degree,
            slots,
            plaintext: profile.plaintext_fixed(),
            root,
            inverse_root,
            inverse_slots,
            mask_l1: 0,
        };
        let mut one_hot = Zeroizing::new(vec![0_u64; slots]);
        one_hot[0] = 1;
        encoding.slots_to_coefficients(&mut one_hot)?;
        let half = (plaintext_modulus - 1) / 2;
        encoding.mask_l1 = one_hot
            .iter()
            .map(|&coefficient| {
                if coefficient > half {
                    plaintext_modulus - coefficient
                } else {
                    coefficient
                }
            })
            .sum();
        Ok(encoding)
    }

    /// Number of scalar slots `S`.
    #[must_use]
    pub const fn slots(&self) -> usize {
        self.slots
    }

    /// Distance `N / S` between coefficients that may be non-zero.
    #[must_use]
    pub const fn stride(&self) -> usize {
        self.degree / self.slots
    }

    /// Whether every ring factor is linear: `S = N`.
    #[must_use]
    pub const fn is_fully_split(&self) -> bool {
        self.slots == self.degree
    }

    /// The pinned primitive `2S`-th root of unity `zeta`.
    #[must_use]
    pub const fn root(&self) -> u64 {
        self.root
    }

    /// Public bound of every encoded slot vector: `linf = (t-1)/2`, `l1 = S*(t-1)/2`.
    #[must_use]
    pub fn vector_bound(&self) -> PlaintextBound {
        let half = (self.plaintext.modulus - 1) / 2;
        PlaintextBound {
            linf: half,
            l1: half * u64::try_from(self.slots).unwrap_or(u64::MAX),
        }
    }

    /// Public bound of every single-slot idempotent: its exact centered `l1` norm.
    #[must_use]
    pub fn mask_bound(&self) -> PlaintextBound {
        PlaintextBound {
            linf: (self.plaintext.modulus - 1) / 2,
            l1: self.mask_l1,
        }
    }

    fn check_profile(&self, profile: &BgvProfile) -> Result<(), BgvError> {
        if &self.identity == profile.identity() {
            Ok(())
        } else {
            Err(BgvError::ProfileMismatch)
        }
    }

    fn slots_to_coefficients(&self, values: &mut [u64]) -> Result<(), BgvError> {
        inverse_negacyclic_ntt_with(
            values,
            &self.plaintext,
            self.inverse_root,
            self.inverse_slots,
        )
        .ok_or(BgvError::Kernel)
    }

    fn spread(
        &self,
        profile: &BgvProfile,
        slot_coefficients: &[u64],
        bound: PlaintextBound,
    ) -> Result<Plaintext, BgvError> {
        let mut coefficients = Zeroizing::new(vec![0_u64; self.degree]);
        for (index, &coefficient) in slot_coefficients.iter().enumerate() {
            coefficients[index * self.stride()] = coefficient;
        }
        Plaintext::with_public_bound(profile, std::mem::take(&mut *coefficients), bound)
    }

    /// Encode up to `S` scalars; missing slots are zero.
    ///
    /// # Errors
    /// [`BgvError::ProfileMismatch`], [`BgvError::SlotOutOfRange`] for more
    /// than `S` values or [`BgvError::NonCanonical`] for a value not below `t`.
    pub fn encode(&self, profile: &BgvProfile, values: &[u64]) -> Result<Plaintext, BgvError> {
        self.check_profile(profile)?;
        if values.len() > self.slots {
            return Err(BgvError::SlotOutOfRange {
                index: values.len(),
                slots: self.slots,
            });
        }
        if let Some(index) = values
            .iter()
            .position(|&value| value >= self.plaintext.modulus)
        {
            return Err(BgvError::NonCanonical { index });
        }
        let mut slots = Zeroizing::new(vec![0_u64; self.slots]);
        slots[..values.len()].copy_from_slice(values);
        self.slots_to_coefficients(&mut slots)?;
        self.spread(profile, &slots, self.vector_bound())
    }

    /// Check that a plaintext lies in the scalar subalgebra.
    ///
    /// # Errors
    /// [`BgvError::ProfileMismatch`] or [`BgvError::OutsideScalarSubalgebra`]
    /// with the first coefficient that is non-zero off the stride.
    pub fn check_scalar_subalgebra(&self, plaintext: &Plaintext) -> Result<(), BgvError> {
        if plaintext.profile_identity() != &self.identity {
            return Err(BgvError::ProfileMismatch);
        }
        let stride = self.stride();
        plaintext
            .coefficients()
            .iter()
            .enumerate()
            .position(|(index, &coefficient)| !index.is_multiple_of(stride) && coefficient != 0)
            .map_or(Ok(()), |index| {
                Err(BgvError::OutsideScalarSubalgebra { index })
            })
    }

    /// Decode the `S` scalars of a plaintext of the scalar subalgebra.
    ///
    /// # Errors
    /// As [`Self::check_scalar_subalgebra`].
    pub fn decode(&self, plaintext: &Plaintext) -> Result<Zeroizing<Vec<u64>>, BgvError> {
        self.check_scalar_subalgebra(plaintext)?;
        let mut slots = Zeroizing::new(
            plaintext
                .coefficients()
                .iter()
                .step_by(self.stride())
                .copied()
                .collect::<Vec<u64>>(),
        );
        forward_negacyclic_ntt_with(&mut slots, &self.plaintext, self.root)
            .ok_or(BgvError::Kernel)?;
        Ok(slots)
    }

    /// The idempotent of one slot, with [`Self::mask_bound`].
    ///
    /// # Errors
    /// [`BgvError::ProfileMismatch`] or [`BgvError::SlotOutOfRange`].
    pub fn slot_mask(&self, profile: &BgvProfile, slot: usize) -> Result<Plaintext, BgvError> {
        self.check_profile(profile)?;
        if slot >= self.slots {
            return Err(BgvError::SlotOutOfRange {
                index: slot,
                slots: self.slots,
            });
        }
        // The slot index may be hidden: build the one-hot vector without branching on it.
        let mut slots = Zeroizing::new(vec![0_u64; self.slots]);
        for (index, value) in slots.iter_mut().enumerate() {
            *value = crate::constant_time::equal_bit_u64(index as u64, slot as u64);
        }
        self.slots_to_coefficients(&mut slots)?;
        self.spread(profile, &slots, self.mask_bound())
    }

    /// The mask that keeps slots `0..count` and zeroes the rest, with [`Self::vector_bound`].
    ///
    /// # Errors
    /// [`BgvError::ProfileMismatch`] or [`BgvError::SlotOutOfRange`] when
    /// `count > S`.
    pub fn prefix_mask(&self, profile: &BgvProfile, count: usize) -> Result<Plaintext, BgvError> {
        self.check_profile(profile)?;
        if count > self.slots {
            return Err(BgvError::SlotOutOfRange {
                index: count,
                slots: self.slots,
            });
        }
        let mut slots = Zeroizing::new(vec![0_u64; self.slots]);
        for (index, value) in slots.iter_mut().enumerate() {
            // One for `index < count`, without branching on a possibly hidden count.
            *value = greater_than_bit_u64(count as u64, index as u64);
        }
        self.slots_to_coefficients(&mut slots)?;
        self.spread(profile, &slots, self.vector_bound())
    }

    /// The slot of the argument that slot `slot` of the image under `X -> X^element` reads.
    ///
    /// # Errors
    /// [`BgvError::SlotOutOfRange`] or [`BgvError::InvalidGaloisElement`] for an even element.
    pub fn slot_source(&self, element: u32, slot: usize) -> Result<usize, BgvError> {
        if slot >= self.slots {
            return Err(BgvError::SlotOutOfRange {
                index: slot,
                slots: self.slots,
            });
        }
        if element.is_multiple_of(2) {
            return Err(BgvError::InvalidGaloisElement);
        }
        let order = 2 * self.slots as u64;
        let exponent = (u64::from(element) % order) * (2 * slot as u64 + 1) % order;
        usize::try_from((exponent - 1) / 2).map_err(|_| BgvError::Kernel)
    }

    /// The Galois elements of the doubling broadcast, in application order.
    ///
    /// `5^(2^i) mod 2N` for `i` in `0..log2(S) - 1`, then `2N - 1`.
    #[must_use]
    pub fn broadcast_elements(&self) -> Vec<u32> {
        let order = 2 * self.degree as u64;
        let mut elements = Vec::with_capacity(self.slots.ilog2() as usize);
        let mut power = 5 % order;
        for _ in 1..self.slots.ilog2() {
            elements.push(u32::try_from(power).unwrap_or(u32::MAX));
            power = power * power % order;
        }
        elements.push(u32::try_from(order - 1).unwrap_or(u32::MAX));
        elements
    }

    /// Select one slot and broadcast it to every slot.
    ///
    /// Multiplies by the idempotent of `slot` and applies the `log2(S)`
    /// doubling steps `x <- x + x(X^g)`. The result holds the selected scalar
    /// in all `S` slots, which is the constant polynomial of that scalar.
    /// Bound: `2^log2(S) * V * l1(mask) + (2^log2(S) - 1) * E_ks`.
    ///
    /// # Errors
    /// [`BgvError::WrongSwitchingKey`] when a Galois key of
    /// [`Self::broadcast_elements`] is missing, and the errors of
    /// [`Self::slot_mask`], [`BgvProfile::mul_plain`],
    /// [`BgvProfile::apply_galois`] and [`BgvProfile::add`].
    pub fn select_and_broadcast(
        &self,
        profile: &BgvProfile,
        ciphertext: &Ciphertext,
        slot: usize,
        keys: &EvaluationKeys,
    ) -> Result<Ciphertext, BgvError> {
        let mask = self.slot_mask(profile, slot)?;
        let mut current = profile.mul_plain(ciphertext, &mask)?;
        for element in self.broadcast_elements() {
            let key = keys.galois(element).ok_or(BgvError::WrongSwitchingKey)?;
            let image = profile.apply_galois(&current, key)?;
            current = profile.add(&current, &image)?;
        }
        Ok(current)
    }

    /// Centered magnitude of a canonical coefficient modulo `t`, branch-free.
    #[must_use]
    pub fn centered_magnitude(&self, coefficient: u64) -> u64 {
        let modulus = self.plaintext.modulus;
        let negative = greater_than_bit_u64(coefficient, (modulus - 1) / 2);
        select_u64(coefficient, modulus.wrapping_sub(coefficient), negative)
    }
}

