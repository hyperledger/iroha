size_t iroha_norito_bridge_retain_exports(void) {
    const size_t count = sizeof(required_exports) / sizeof(required_exports[0]);
    for (size_t index = 0; index < count; ++index) {
        if (required_exports[index] == NULL) {
            return 0;
        }
    }
    return count;
}
